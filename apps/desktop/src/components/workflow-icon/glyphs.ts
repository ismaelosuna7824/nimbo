/** The glyph with this ID, or undefined for MASCOT_GLYPH and unknown IDs (both rendered as the mascot). */
export function glyphById(id: string): PixelGlyphDef | undefined {
  return Object.hasOwn(BY_ID, id) ? BY_ID[id] : undefined
}
