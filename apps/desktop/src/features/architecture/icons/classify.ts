const PLUMBING_EXACT: Record<string, true> = Object.fromEntries(PLUMBING_TYPES.map((t) => [t, true]));

/** Utility providers whose resources never get a card of their own. */
const PLUMBING_PREFIXES = ["random_", "archive_", "null_", "time_", "tls_", "local_", "terraform_", "template_", "cloudinit_", "http", "external", "modtm_"];

export function isPlumbing(_provider: ArchProvider, resourceType: string): boolean {
  const t = baseType(resourceType);
  if (PLUMBING_EXACT[t]) return true;
  return PLUMBING_PREFIXES.some((p) => t.startsWith(p));
}
