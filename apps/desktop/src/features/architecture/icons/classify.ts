/** Strips the `data.` prefix so data sources classify like their resource. */
export function baseType(resourceType: string): string {
  return resourceType.startsWith("data.") ? resourceType.slice(5) : resourceType;
}

/** Provider owning a Terraform type (`aws_*`, `azurerm_*`/`azuread_*`, `google_*`, `oci_*`). */
export function providerOfType(resourceType: string): ArchProvider | undefined {
  const t = baseType(resourceType);
  if (t.startsWith("aws_")) return "aws";
  if (t.startsWith("azurerm_") || t.startsWith("azuread_") || t.startsWith("azapi_")) return "azure";
  if (t.startsWith("google_")) return "gcp";
  if (t.startsWith("oci_")) return "oci";
  return undefined;
}

