export function archIconFor(provider: ArchProvider, resourceType: string): ArchIcon {
  const { slug, generic } = archIconSlugFor(provider, resourceType);
  const [service, short, iconCategory] = ICONS[slug];
  const named = TYPE_NAMES[baseType(resourceType)];
  const category = archCategoryOf(provider, resourceType);
  return {
    src: archIconSrc(slug),
    service: named?.[0] ?? service,
    short: named?.[1] ?? short,
    category: category === "other" ? iconCategory : category,
    generic,
  };
}

/** Official provider logo (AWS / Azure / Google Cloud / OCI). */
export function providerLogo(provider: ArchProvider): string {
  return archIconSrc(`logo-${provider}`);
}

/** Official group/container label icon of a provider, when the provider defines one. */
export function groupIcon(provider: ArchProvider, kind: ArchGroupKind): string | undefined {
  const slug = GROUP_ICONS[provider][kind];
  return slug ? archIconSrc(slug) : undefined;
}

/** Provider-neutral actor icon (users, internet, clients, external services). */
export function actorIcon(kind: ArchActorKind): ArchIcon {
  const slug = `actor-${kind}` as const;
  const [service, short, category] = ICONS[slug];
  return { src: archIconSrc(slug), service, short, category, generic: false };
}
