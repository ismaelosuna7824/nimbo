/** The inspector of a Kubernetes workspace's selected object or chart (null when nothing of the graph is selected). */
export function KubeInspector() {
  const graph = useWorkflowStore((s) => s.workflow!.kubernetes?.graph)
  const selected = useWorkflowStore((s) => s.selectedNodeId)
  const node = graph?.nodes.find((n) => n.id === selected)
  if (graph && selected && graph.charts?.some((c) => c.id === selected)) return <ChartInspector key={selected} graph={graph} chartId={selected} />
  if (!node) return null
  return <NodeInspector key={node.id} node={node} />
}

function NodeInspector({ node }: { node: KubeNode }) {
  const workflowId = useWorkflowStore((s) => s.workflow!.id)
  const diagnostics = useWorkflowStore((s) => s.workflow!.diagnostics).filter((d) => d.nodeId === node.id)
  const status = useWorkflowStore((s) => s.kube?.workloads.find((w) => w.nodeId === node.id))
  // Keyed by the node too: an edit re-renders the object, and where its fields are written may change with it.
  const fields = useQuery({
    queryKey: ["kubernetes-fields", workflowId, node],
    queryFn: () => api.kubernetesFields(workflowId, node.id),
    placeholderData: keepPreviousData,
  })
  return (
    <KubeFieldsContext value={{ node, fields: fields.data?.fields }}>
      <div className="flex h-full flex-col" data-testid="k8s-inspector" data-node={node.id}>
        <Header node={node} status={status} />
        <div className="flex min-h-0 flex-1 flex-col gap-5 overflow-y-auto p-4">
          {diagnostics.length > 0 && (
            <div className="-mx-3 flex flex-col rounded-lg border">
              {diagnostics.map((d, i) => (
                <DiagnosticRow key={i} diagnostic={d} onSelect={d.file ? () => revealFiles("", d.file, d.line) : undefined} />
              ))}
            </div>
          )}
          {fields.isError && <p className="text-[11px] text-destructive">Couldn't tell where each field is written: {fields.error.message}</p>}
          {!node.editable && node.sourceKind !== "helm" && (
            <p className="rounded-md bg-muted px-3 py-2 text-xs text-muted-foreground">
              Generated by the {node.sourceKind} source: fields that can't be written back show why. Edit the rest in code.
            </p>
          )}
          {status && status.state !== "absent" && <Live status={status} />}
          {node.workload ? (
            <WorkloadForm node={node} />
          ) : node.kind === "Service" && node.service ? (
            <ServiceForm node={node} />
          ) : node.routes ? (
            <IngressForm node={node} />
          ) : node.kind === "HorizontalPodAutoscaler" && node.scaler ? (
            <HpaForm node={node} />
          ) : node.kind === "PersistentVolumeClaim" ? (
            <ClaimForm node={node} />
          ) : (
            <Facts node={node} />
          )}
        </div>
      </div>
    </KubeFieldsContext>
  )
}

function Header({ node, status }: { node: KubeNode; status?: KubeWorkloadStatus }) {
  const chart = useWorkflowStore((s) => s.workflow!.kubernetes?.sources[node.source]?.chart)
  const vendored = useWorkflowStore((s) => (node.chart ? s.workflow!.kubernetes?.graph.charts?.find((c) => c.id === node.chart) : undefined))
  const select = useWorkflowStore((s) => s.select)
  const restartable = node.workload && node.kind !== "Job" && node.kind !== "CronJob" && node.kind !== "Pod"
  const clusterUp = useWorkflowStore((s) => s.kube?.cluster.state === "running")
  return (
    <div className="flex items-start gap-3 border-b p-4">
      <span className="flex size-10 shrink-0 items-center justify-center rounded-xl border bg-background">
        <K8sIcon icon={node.kind} size={26} />
      </span>
      <div className="min-w-0 flex-1">
        <div className="truncate font-heading text-base leading-tight font-medium">{node.name}</div>
        <div className="truncate font-mono text-[11px] text-muted-foreground">
          {node.namespace ? `${node.namespace} · ` : ""}
          {node.apiVersion}
        </div>
        <div className="mt-1.5 flex flex-wrap items-center gap-1.5">
          <Badge variant="secondary">{node.kind}</Badge>
          {vendored ? (
            <Badge variant="outline" className="gap-1" asChild>
              <button type="button" data-testid="k8s-inspector-chart" title="Show the chart's release" onClick={() => select(vendored.id)}>
                <TechIcon icon="helm" size={12} />
                {vendored.chart} {vendored.version}
              </button>
            </Badge>
          ) : node.sourceKind === "helm" ? (
            <Badge variant="outline" className="gap-1">
              <TechIcon icon="helm" size={12} />
              {chart ? `${chart.name} ${chart.version}` : node.sourcePath}
            </Badge>
          ) : (
            <Badge variant="outline">{node.sourceKind}</Badge>
          )}
          {status?.rollout && <Badge variant="outline">{status.rollout}</Badge>}
        </div>
      </div>
      <div className="flex items-center gap-0.5">
        {node.file && (
          <Tooltip>
            <TooltipTrigger asChild>
              <Button variant="ghost" size="icon-sm" aria-label="Open in code" onClick={() => revealFiles("", node.file, node.line)}>
                <Code2Icon />
              </Button>
            </TooltipTrigger>
            <TooltipContent>
              Open {node.file}
              {node.line ? `:${node.line}` : ""}
            </TooltipContent>
          </Tooltip>
        )}
        {restartable && (
          <Tooltip>
            <TooltipTrigger asChild>
              <Button variant="ghost" size="icon-sm" aria-label="Restart" disabled={!clusterUp} onClick={() => void restartWorkload(node)}>
                <RotateCwIcon />
              </Button>
            </TooltipTrigger>
            <TooltipContent>Restart its pods (rollout restart)</TooltipContent>
          </Tooltip>
        )}
        <Tooltip>
          <TooltipTrigger asChild>
            <Button variant="ghost" size="icon-sm" aria-label="Delete" onClick={() => void deleteObject(node)}>
              <Trash2Icon />
            </Button>
          </TooltipTrigger>
          <TooltipContent>Delete (⌫)</TooltipContent>
        </Tooltip>
      </div>
    </div>
  )
}

const TONE: Record<string, string> = {
  ok: "bg-emerald-500",
  pending: "bg-amber-500",
  error: "bg-destructive",
  done: "bg-muted-foreground/50",
}

/** Pods of a workload on the local cluster: phase, readiness, restarts and why they are unhappy. */
function Live({ status }: { status: KubeWorkloadStatus }) {
  return (
    <Section title="Live" icon={<RadioIcon className="size-3.5 text-sky-500" />}>
      <p className="text-xs" data-testid="k8s-inspector-rollout">
        {status.ready}/{status.desired} ready{status.rollout ? ` · ${status.rollout}` : ""}
      </p>
      {status.pods.length === 0 ? (
        <p className="text-[11px] text-muted-foreground">No pods.</p>
      ) : (
        <ul className="flex flex-col gap-1.5">
          {status.pods.map((p) => {
            const dot = podDot(p)
            const unhappy = p.containers.find((c) => c.reason || c.lastReason)
            return (
              <li key={p.name} data-testid="k8s-inspector-pod" data-tone={dot.tone} className="flex flex-col gap-0.5 rounded-md border px-2 py-1.5 text-xs">
                <div className="flex items-center gap-2">
                  <span className={cn("size-2 shrink-0 rounded-full", TONE[dot.tone])} />
                  <span className="truncate font-mono">{p.name}</span>
                  <span className="ml-auto shrink-0 text-muted-foreground">
                    {p.phase}
                    {p.ready ? " · ready" : ""}
                  </span>
                </div>
                {(dot.reason || p.restarts > 0) && (
                  <span className={cn("text-[11px]", dot.tone === "error" ? "text-destructive" : "text-amber-600 dark:text-amber-400")}>
                    {[dot.reason, p.restarts > 0 ? `restarted ${p.restarts}×` : undefined, unhappy?.lastReason && unhappy.lastReason !== dot.reason ? `last: ${unhappy.lastReason}` : undefined].filter(Boolean).join(" · ")}
                  </span>
                )}
                {p.message && <span className="text-[11px] text-muted-foreground">{p.message}</span>}
              </li>
            )
          })}
        </ul>
      )}
    </Section>
  )
}

/** Objects without a form: their facts, edited in code. */
function Facts({ node }: { node: KubeNode }) {
  const facts: [string, string | undefined][] = [
    ["Keys", node.data?.length ? node.data.join(", ") : node.kind === "ConfigMap" || node.kind === "Secret" ? "none" : undefined],
    ["Min available", node.disruption?.minAvailable],
    ["Max unavailable", node.disruption?.maxUnavailable],
    ["Selector", node.disruption?.selector && Object.entries(node.disruption.selector).map(([k, v]) => `${k}=${v}`).join(", ")],
    ["Storage class", node.storage?.storageClass],
    ["Size", node.storage?.size],
    ["Provisioner", node.storage?.provisioner],
    ["Labels", node.labels && Object.entries(node.labels).map(([k, v]) => `${k}=${v}`).join(", ")],
    ["File", node.file && `${node.file}${node.line ? `:${node.line}` : ""}`],
  ]
  return (
    <Section title="Details" icon={<FileTextIcon className="size-3.5" />}>
      <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1 text-xs">
        {facts
          .filter(([, v]) => v)
          .map(([k, v]) => (
            <div key={k} className="contents">
              <dt className="text-muted-foreground">{k}</dt>
              <dd className="truncate font-mono" title={v}>
                {v}
              </dd>
            </div>
          ))}
      </dl>
      {node.kind === "Secret" && <p className="text-[11px] text-muted-foreground">Values never leave your files; edit them in code.</p>}
      {node.file && (
        <Button variant="outline" size="xs" className="self-start" onClick={() => revealFiles("", node.file, node.line)}>
          <Code2Icon />
          Open in code
        </Button>
      )}
    </Section>
  )
}

const SOURCE_LABEL: Record<KubeSource["kind"], string> = { manifests: "Manifests", kustomize: "Kustomize", helm: "Helm chart" }

/** The workflow's sources in apply order (Overview of a Kubernetes workspace). */
export function KubeSources({ sources }: { sources: KubeSource[] }) {
  if (sources.length === 0) return null
  return (
    <div className="flex flex-col gap-1.5" data-testid="k8s-overview-sources">
      <span className="text-xs font-medium">Sources</span>
      <ul className="flex flex-col gap-1">
        {sources.map((s, i) => (
          <li key={`${s.kind}:${s.path}`} data-testid={`k8s-overview-source-${i}`} className="flex items-center gap-2 rounded-md border px-2 py-1.5 text-xs">
            {s.kind === "helm" ? <TechIcon icon="helm" size={16} /> : <TechIcon icon="kubernetes" size={16} />}
            <div className="min-w-0 flex-1">
              <div className="flex items-center gap-1.5">
                <span className="font-medium">{SOURCE_LABEL[s.kind]}</span>
                {s.chart && (
                  <span className="truncate font-mono text-[11px] text-muted-foreground">
                    {s.chart.name} {s.chart.version}
                  </span>
                )}
              </div>
              <button type="button" className="block max-w-full truncate font-mono text-[11px] text-muted-foreground hover:text-foreground hover:underline" onClick={() => revealFiles(s.path)}>
                {s.path}
                {s.release ? ` · release ${s.release}` : ""}
                {s.namespace ? ` · ns ${s.namespace}` : ""}
              </button>
              {s.error && <p className="text-[11px] text-destructive">{s.error}</p>}
            </div>
            <span className="shrink-0 text-[11px] text-muted-foreground tabular-nums">
              {s.objects} object{s.objects === 1 ? "" : "s"}
            </span>
          </li>
        ))}
      </ul>
    </div>
  )
}

