// Field paths and values the Kubernetes inspector writes through PATCH …/kubernetes/objects, and whether a
// path can be written (GET …/kubernetes/fields). Kept free of React so it can be tested.

import type { KubeContainer, KubeEnv, KubeEnvFrom, KubeField, KubeNode, KubeProbe, KubeRoute, KubeScaler, KubeServicePort, KubeVolume, KubeVolumeMount } from "@/lib/api/types"

/** Path of the pod spec inside an object of `kind`. */
export function podSpecPath(kind: string): string {
  if (kind === "Pod") return "spec"
  if (kind === "CronJob") return "spec.jobTemplate.spec.template.spec"
  return "spec.template.spec"
}

export function containerPath(kind: string, name: string): string {
  return `${podSpecPath(kind)}.containers[name=${name}]`
}

export const PROBES = [
  { key: "liveness", field: "livenessProbe", label: "Liveness" },
  { key: "readiness", field: "readinessProbe", label: "Readiness" },
  { key: "startup", field: "startupProbe", label: "Startup" },
] as const

/** Whether a path can be written, and why not. */
export interface FieldAccess {
  editable: boolean
  reason?: string
  /** The field that decided (where it is written / why it is read-only). */
  field?: KubeField
}

const under = (path: string, parent: string) => path.startsWith(`${parent}.`) || path.startsWith(`${parent}[`)

/**
 * The access of `path`: its own field when the daemon listed it, else a read-only field inside it (a list whose
 * items come from a template expression) or around it, else the object's: plain manifests and Kustomize objects
 * create missing paths, Helm maps them to values when it can (the daemon says why when it can't).
 */
export function fieldAccess(fields: readonly KubeField[] | undefined, path: string, node: KubeNode): FieldAccess {
  const list = fields ?? []
  const own = list.find((f) => f.path === path)
  if (own) return { editable: own.editable, reason: own.reason, field: own }
  const blocked = list.find((f) => !f.editable && (under(f.path, path) || under(path, f.path)))
  if (blocked) return { editable: false, reason: blocked.reason, field: blocked }
  const near = list.find((f) => under(f.path, path) || under(path, f.path))
  if (node.editable || node.sourceKind === "helm") return { editable: true, field: near }
  return { editable: false, reason: "Generated by the source: edit it in code" }
}

/** "values.yaml: image.tag" for a field written to Helm values. */
export function valuesHint(field: KubeField | undefined): string | undefined {
  if (!field || field.via !== "values" || !field.valuesKeys?.length) return undefined
  const file = field.file?.split("/").pop() ?? "values.yaml"
  return `${file}: ${field.valuesKeys.join(", ")}`
}

/** A port written as a number when it is one, else as a port name. */
export function portValue(port: string): number | string {
  return /^\d+$/.test(port) ? Number(port) : port
}

/** The probe object of a container spec. */
export function probeObject(p: KubeProbe): Record<string, unknown> {
  const port = portValue(p.port ?? "")
  const handler: Record<string, unknown> =
    p.type === "http"
      ? { httpGet: { path: p.path || "/", port } }
      : p.type === "tcp"
        ? { tcpSocket: { port } }
        : p.type === "grpc"
          ? { grpc: { port } }
          : { exec: { command: ["sh", "-c", p.command ?? ""] } }
  const timing = {
    initialDelaySeconds: p.initialDelaySeconds,
    periodSeconds: p.periodSeconds,
    timeoutSeconds: p.timeoutSeconds,
    failureThreshold: p.failureThreshold,
  }
  return { ...handler, ...Object.fromEntries(Object.entries(timing).filter(([, v]) => v !== undefined)) }
}

export function containerPorts(ports: KubeContainer["ports"]): Record<string, unknown>[] {
  return ports.map((p) => ({ ...(p.name && { name: p.name }), containerPort: p.containerPort, ...(p.protocol && p.protocol !== "TCP" && { protocol: p.protocol }) }))
}

export function envFromList(list: KubeEnvFrom[]): Record<string, unknown>[] {
  return list.map((e) => ({ ...(e.prefix && { prefix: e.prefix }), [e.kind === "Secret" ? "secretRef" : "configMapRef"]: { name: e.name } }))
}

export function mountList(list: KubeVolumeMount[]): Record<string, unknown>[] {
  return list.map((m) => ({ name: m.name, mountPath: m.mountPath, ...(m.subPath && { subPath: m.subPath }), ...(m.readOnly && { readOnly: true }) }))
}

/** Volume kinds the inspector writes; the others (hostPath, projected…) are edited in code. */
export const EDITABLE_VOLUME: Partial<Record<KubeVolume["kind"], true>> = { configMap: true, secret: true, persistentVolumeClaim: true, emptyDir: true }

export function volumeObject(v: KubeVolume): Record<string, unknown> {
  switch (v.kind) {
    case "configMap":
      return { name: v.name, configMap: { name: v.source ?? "" } }
    case "secret":
      return { name: v.name, secret: { secretName: v.source ?? "" } }
    case "persistentVolumeClaim":
      return { name: v.name, persistentVolumeClaim: { claimName: v.source ?? "" } }
    default:
      return { name: v.name, emptyDir: {} }
  }
}

export interface ObjectPatch {
  set: Record<string, unknown>
  unset: string[]
}

const same = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b)

/**
 * Volume edits item by item (`volumes[name=x]`), so volumes the inspector can't show in full (hostPath, projected)
 * stay as written.
 */
export function volumesPatch(kind: string, before: KubeVolume[], after: KubeVolume[]): ObjectPatch {
  const base = `${podSpecPath(kind)}.volumes`
  const old = new Map(before.map((v) => [v.name, v]))
  const names = new Set(after.map((v) => v.name))
  const out: ObjectPatch = { set: {}, unset: [] }
  for (const v of before) if (!names.has(v.name)) out.unset.push(`${base}[name=${v.name}]`)
  for (const v of after) {
    if (!v.name || !EDITABLE_VOLUME[v.kind] || same(old.get(v.name), v)) continue
    out.set[`${base}[name=${v.name}]`] = volumeObject(v)
  }
  return out
}

/**
 * Environment edits variable by variable (`env[name=X].value` / `.valueFrom`), so redacted secret values and
 * field references stay as written.
 */
export function envPatch(container: string, before: KubeEnv[], after: KubeEnv[]): ObjectPatch {
  const base = `${container}.env`
  const old = new Map(before.map((e) => [e.name, e]))
  const names = new Set(after.map((e) => e.name))
  const out: ObjectPatch = { set: {}, unset: [] }
  for (const e of before) if (!names.has(e.name)) out.unset.push(`${base}[name=${e.name}]`)
  for (const e of after) {
    if (!e.name) continue
    const prev = old.get(e.name)
    if (prev && same(prev, e)) continue
    const at = `${base}[name=${e.name}]`
    if (e.from && (e.from.kind === "ConfigMap" || e.from.kind === "Secret")) {
      const ref = e.from.kind === "Secret" ? "secretKeyRef" : "configMapKeyRef"
      out.set[`${at}.valueFrom`] = { [ref]: { name: e.from.name ?? "", key: e.from.key ?? "" } }
      if (prev && !prev.from) out.unset.push(`${at}.value`)
    } else if (!e.from) {
      // A redacted secret without a new value keeps the stored one.
      if (e.secret && e.value === undefined) continue
      out.set[`${at}.value`] = e.value ?? ""
      if (prev?.from) out.unset.push(`${at}.valueFrom`)
    }
  }
  return out
}

export function servicePorts(ports: KubeServicePort[]): Record<string, unknown>[] {
  return ports.map((p) => ({
    ...(p.name && { name: p.name }),
    port: p.port,
    ...(p.targetPort && { targetPort: portValue(p.targetPort) }),
    ...(p.nodePort && { nodePort: p.nodePort }),
    ...(p.protocol && p.protocol !== "TCP" && { protocol: p.protocol }),
  }))
}

/**
 * Ingress `spec.rules` from flat routes: one rule per host (first-seen order), Prefix paths. `defaultPort` gives the
 * backend port of a route without one (the Service's first port).
 */
export function ingressRules(routes: KubeRoute[], defaultPort: (service: string) => number | string): Record<string, unknown>[] {
  const hosts = new Map<string, Record<string, unknown>[]>()
  for (const r of routes) {
    const port = r.port ? portValue(r.port) : defaultPort(r.service)
    const path = {
      path: r.path || "/",
      pathType: "Prefix",
      backend: { service: { name: r.service, port: typeof port === "number" ? { number: port } : { name: port } } },
    }
    const host = r.host ?? ""
    hosts.set(host, [...(hosts.get(host) ?? []), path])
  }
  return [...hosts].map(([host, paths]) => ({ ...(host && { host }), http: { paths } }))
}

/** HPA `spec.metrics` (autoscaling/v2) for CPU and memory utilization targets. */
export function hpaMetrics(s: Pick<KubeScaler, "cpu" | "memory">): Record<string, unknown>[] {
  const metric = (name: string, pct: number) => ({ type: "Resource", resource: { name, target: { type: "Utilization", averageUtilization: pct } } })
  return [...(s.cpu ? [metric("cpu", s.cpu)] : []), ...(s.memory ? [metric("memory", s.memory)] : [])]
}
