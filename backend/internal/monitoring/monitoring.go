// Package monitoring generates the monitoring Add monitoring puts in a
// workflow (POST /workflows/{id}/monitoring): for docker workflows a
// Prometheus, Grafana and cAdvisor compose file with its configuration,
// alert rules and dashboards; for Kubernetes workflows the
// kube-prometheus-stack chart plus ServiceMonitors/PodMonitors,
// workload-scoped PrometheusRules and Grafana dashboard ConfigMaps for the
// workflow's own workloads. The generators are pure: they read the
// rendered project and return files; the API writes them.
package monitoring

import (
	"crypto/rand"
	"encoding/json"
	"math/big"
)

// generatedMarker starts every generated file: Update monitoring rewrites
// files that carry it and refuses to replace a user's own file.
const generatedMarker = "Generated by Nimbo (Add monitoring)"

// grafanaUser is the Grafana admin user.
const grafanaUser = "admin"

// datasourceUID is the uid of the Prometheus data source the dashboards
// use: kube-prometheus-stack provisions it (grafana.sidecar.datasources.uid)
// and the docker provisioning file declares it.
const datasourceUID = "prometheus"

// NewPassword returns a random 24-character alphanumeric password.
func NewPassword() string {
	const alphabet = "abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"
	out := make([]byte, 24)
	for i := range out {
		n, err := rand.Int(rand.Reader, big.NewInt(int64(len(alphabet))))
		if err != nil {
			panic(err) // crypto/rand never fails on supported platforms
		}
		out[i] = alphabet[n.Int64()]
	}
	return string(out)
}

// ---------------------------------------------------------------------------
// Grafana dashboards (JSON model, schemaVersion 39: Grafana 11 and later).

type gridPos struct{ X, Y, W, H int }

type target struct{ legend, expr string }

func datasource() map[string]any {
	return map[string]any{"type": "prometheus", "uid": datasourceUID}
}

// timeseries is a time series panel; overrides map a legend to a fixed
// color and a dashed line (requests, limits, targets).
func timeseries(id int, title, description, unit string, pos gridPos, dashed map[string]string, targets ...target) map[string]any {
	ts := make([]map[string]any, len(targets))
	for i, t := range targets {
		ts[i] = map[string]any{
			"datasource": datasource(), "expr": t.expr, "legendFormat": t.legend,
			"refId": string(rune('A' + i)), "range": true,
		}
	}
	var overrides []map[string]any
	for _, t := range targets {
		color, ok := dashed[t.legend]
		if !ok {
			continue
		}
		overrides = append(overrides, map[string]any{
			"matcher": map[string]any{"id": "byName", "options": t.legend},
			"properties": []map[string]any{
				{"id": "color", "value": map[string]any{"mode": "fixed", "fixedColor": color}},
				{"id": "custom.lineStyle", "value": map[string]any{"fill": "dash", "dash": []int{10, 10}}},
				{"id": "custom.fillOpacity", "value": 0},
			},
		})
	}
	if overrides == nil {
		overrides = []map[string]any{}
	}
	return map[string]any{
		"id": id, "type": "timeseries", "title": title, "description": description,
		"datasource": datasource(),
		"gridPos":    map[string]int{"x": pos.X, "y": pos.Y, "w": pos.W, "h": pos.H},
		"fieldConfig": map[string]any{
			"defaults": map[string]any{
				"unit": unit, "min": 0,
				"custom": map[string]any{"lineWidth": 2, "fillOpacity": 10, "showPoints": "never", "spanNulls": true},
			},
			"overrides": overrides,
		},
		"options": map[string]any{
			"legend":  map[string]any{"displayMode": "list", "placement": "bottom", "showLegend": true},
			"tooltip": map[string]any{"mode": "multi", "sort": "desc"},
		},
		"targets": ts,
	}
}

// row is a row panel repeated for every selected value of variable.
func row(id int, title, variable string, y int) map[string]any {
	return map[string]any{
		"id": id, "type": "row", "title": title, "collapsed": false, "repeat": variable,
		"gridPos": map[string]int{"x": 0, "y": y, "w": 24, "h": 1}, "panels": []any{},
	}
}

// queryVar is a query variable over a Prometheus label (multi-select,
// All by default).
func queryVar(name, label, query, regex string) map[string]any {
	return map[string]any{
		"name": name, "label": label, "type": "query", "datasource": datasource(),
		"query":      map[string]any{"query": query, "refId": "PrometheusVariableQueryEditor-VariableQuery", "qryType": 1},
		"definition": query, "regex": regex, "refresh": 2, "sort": 1,
		"multi": true, "includeAll": true,
		"current": map[string]any{"selected": true, "text": []string{"All"}, "value": []string{"$__all"}},
	}
}

// customVar is a custom variable listing fixed values (multi-select, All
// by default).
func customVar(name, label string, values []string) map[string]any {
	opts := make([]map[string]any, 0, len(values))
	q := ""
	for i, v := range values {
		opts = append(opts, map[string]any{"selected": false, "text": v, "value": v})
		if i > 0 {
			q += ","
		}
		q += v
	}
	return map[string]any{
		"name": name, "label": label, "type": "custom", "query": q, "options": opts,
		"multi": true, "includeAll": true,
		"current": map[string]any{"selected": true, "text": []string{"All"}, "value": []string{"$__all"}},
	}
}

// dashboard is a dashboard JSON document.
func dashboard(uid, title, description string, tags []string, vars []map[string]any, panels []map[string]any) []byte {
	d := map[string]any{
		"uid": uid, "title": title, "description": description, "tags": tags,
		"editable": true, "schemaVersion": 39, "version": 1,
		"time": map[string]any{"from": "now-1h", "to": "now"}, "refresh": "30s",
		"timezone": "browser", "graphTooltip": 1,
		"templating":  map[string]any{"list": vars},
		"annotations": map[string]any{"list": []any{}},
		"panels":      panels,
	}
	out, err := json.MarshalIndent(d, "", "  ")
	if err != nil {
		panic(err) // maps of strings and numbers always marshal
	}
	return append(out, '\n')
}
