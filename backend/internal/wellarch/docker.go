package wellarch

import "github.com/ismaelosuna7824/nimbo/backend/internal/model"

func dockerGuide() Guide {
	return Guide{
		Platform:  "docker",
		Name:      "Docker Compose",
		Framework: "Docker build and Compose production best practices",
		Sources: []Source{
			{"Docker build best practices", "https://docs.docker.com/build/building/best-practices/"},
			{"Use Compose in production", "https://docs.docker.com/compose/how-tos/production/"},
			{"Compose deploy specification", "https://docs.docker.com/reference/compose-file/deploy/"},
			{"OWASP API Security Top 10 2023", "https://owasp.org/API-Security/editions/2023/en/0x11-t10"},
		},
		Pillars: []PillarGuide{
			pillar(model.PillarSecurity,
				"Run containers unprivileged with a minimal, read-only footprint and keep secrets out of images and env.",
				p("Run as a non-root user",
					"A root process that escapes the container is root on the host.",
					[]string{"Add USER app (non-zero UID) in the Dockerfile or set user: \"1000:1000\" in compose."},
					"dk_root_user"),
				p("Drop capabilities and block privilege escalation",
					"Default capabilities (NET_RAW, etc.) are more than most apps need.",
					[]string{
						"Set cap_drop: [ALL] and add back only what's needed with cap_add.",
						"Set security_opt: [\"no-new-privileges:true\"]; never privileged: true.",
					},
					"dk_cap_add", "dk_net_raw", "dk_no_new_privileges", "dk_privileged", "dk_hardening"),
				p("Use a read-only root filesystem",
					"An immutable filesystem stops attackers persisting tooling.",
					[]string{"Set read_only: true with tmpfs: [/tmp] for scratch space."},
					"dk_read_only"),
				p("Keep secrets out of environment and images",
					"Env vars leak via inspect, logs and child processes; build args stay in image layers.",
					[]string{"Use top-level secrets: (file) mounted at /run/secrets; use RUN --mount=type=secret in builds."},
					"dk_secret_env", "dk_secret_build", "dk_secret_file"),
				p("Don't share host namespaces or the Docker socket",
					"Mounting /var/run/docker.sock or host namespaces gives host control.",
					[]string{"Avoid network_mode: host, pid: host, ipc: host, privileged devices and docker.sock mounts; avoid binding sensitive host dirs."},
					"dk_docker_sock", "dk_host_ipc", "dk_host_uts", "dk_host_userns", "dk_host_dirs", "dk_devices"),
				p("Publish ports only where needed",
					"Published database ports on 0.0.0.0 are reachable from the LAN.",
					[]string{"Keep databases on an internal network; bind dev ports to 127.0.0.1 (\"127.0.0.1:5432:5432\")."},
					"dk_db_published", "dk_port_interface", "dk_network_internal"),
				p("Front exposed services with a reverse proxy that rate limits and terminates TLS",
					"An app port published straight to the network has no request limits or TLS; the local equivalent of a cloud WAF is a proxy in front (OWASP API4:2023).",
					[]string{
						"Publish only the proxy (nginx limit_req_zone/limit_req, Traefik rateLimit middleware, Caddy) and keep app and data services on internal networks.",
						"Terminate TLS 1.2+ at the proxy for anything beyond localhost; local dev on 127.0.0.1 can stay plain HTTP.",
						"Skip the proxy for a single private dev service with no exposure.",
					},
					"dk_db_published", "dk_port_interface"),
			),
			pillar(model.PillarReliability,
				"Healthchecks, ordered startup, restart policies and durable named volumes.",
				p("Define healthchecks",
					"Docker can only report and react to health it can measure.",
					[]string{"Add healthcheck: { test, interval, timeout, retries, start_period } to every long-running service."},
					"dk_missing_healthcheck", "dk_no_healthcheck", "dk_healthcheck_timing"),
				p("Start dependents only when dependencies are healthy",
					"A container running is not a database ready to accept connections.",
					[]string{"Use depends_on: { db: { condition: service_healthy } }; service_completed_successfully for one-shot migrations."},
					"dk_depends_healthy", "dk_depends_completed"),
				p("Set a restart policy",
					"Crashed services should come back without manual intervention.",
					[]string{"Set restart: unless-stopped (or on-failure) on long-running services."},
					"dk_no_restart"),
				p("Store data in named volumes",
					"Anonymous volumes are orphaned and easily lost on recreate.",
					[]string{"Declare top-level volumes: and mount them (e.g. pgdata:/var/lib/postgresql/data)."},
					"dk_anon_volume"),
				p("Use an init process",
					"PID 1 must reap zombies and forward signals for clean shutdowns.",
					[]string{"Set init: true or use an init like tini as ENTRYPOINT; use exec-form CMD."},
					"dk_no_init", "dk_shell_form"),
			),
			pillar(model.PillarPerformance,
				"Bound resources, build lean images and scale stateless services behind a proxy.",
				p("Set CPU, memory and PID limits",
					"One runaway container can starve the whole host.",
					[]string{"Set deploy.resources.limits { cpus, memory } (or mem_limit/cpus) and pids_limit."},
					"dk_no_limits", "dk_pids_limit"),
				p("Use multi-stage builds and slim bases",
					"Smaller images pull and start faster and have fewer CVEs.",
					[]string{"Build in a builder stage and COPY --from=builder into a slim/distroless base."},
					"dk_single_stage", "dk_heavy_base"),
				p("Order layers for cache reuse",
					"Copying dependency manifests before source keeps installs cached.",
					[]string{"COPY package files, install, then COPY source; use RUN --mount=type=cache and a .dockerignore."},
					"dk_layer_order", "dk_cache_mount", "dk_dockerignore"),
				p("Scale stateless services with replicas behind a proxy",
					"Fixed host ports prevent running more than one replica.",
					[]string{"Do not publish host ports on scaled services; set deploy.replicas and front them with a reverse proxy (nginx/traefik) on a shared network. Matters mostly for production-like setups."},
					"dk_port_clash"),
			),
			pillar(model.PillarCost,
				"Keep images, caches and logs small so local disks and registries don't fill up.",
				p("Rotate container logs",
					"The json-file driver grows unbounded by default.",
					[]string{"Set logging: { driver: json-file, options: { max-size: \"10m\", max-file: \"3\" } }."},
					"dk_log_rotation"),
				p("Clean package caches in the same layer",
					"Caches left in layers bloat every pull.",
					[]string{"Use apt-get install --no-install-recommends && rm -rf /var/lib/apt/lists/*, apk --no-cache, pip --no-cache-dir."},
					"dk_apt_install", "dk_apk_cache", "dk_pip_cache", "dk_update_alone"),
				p("Prefer slim base images",
					"Smaller images save registry storage and bandwidth.",
					[]string{"Use -slim, -alpine or distroless variants where compatible."},
					"dk_heavy_base"),
				p("Exclude build-context noise",
					"Large build contexts waste time and space.",
					[]string{"Add a .dockerignore excluding .git, node_modules and build output."},
					"dk_dockerignore"),
			),
			pillar(model.PillarOperations,
				"Reproducible, pinned images and declarative, environment-driven configuration.",
				p("Pin image tags (or digests)",
					":latest changes underneath you and breaks reproducibility.",
					[]string{"Use explicit tags like postgres:16.4 or @sha256 digests for production."},
					"dk_latest_tag"),
				p("Layer environments over one base",
					"Externalised config lets the same compose file run in every environment; duplicated per-environment files drift.",
					[]string{
						"Keep compose.yaml as the base and put each environment's changes in compose.<env>.yaml and/or .env.<env>; use env_file and ${VAR:-default}.",
						"Production overlays set restart, limits and secrets: and never bind-mount source code; bind mounts and debug ports stay in the dev overlay.",
					},
					"dk_missing_env_file", "dk_unresolved_var", "dk_environment_file"),
				p("Use explicit networks",
					"The default bridge lacks DNS-based service discovery and isolation.",
					[]string{"Declare user-defined networks: and attach services; separate frontend/backend networks."},
					"dk_default_bridge"),
				p("Prefer COPY and explicit WORKDIR",
					"ADD has surprising URL/tar semantics; explicit WORKDIR avoids path bugs.",
					[]string{"Use COPY for local files and set WORKDIR /app."},
					"dk_add", "dk_workdir"),
			),
		},
	}
}
