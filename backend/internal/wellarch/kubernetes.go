package wellarch

import "github.com/ismaelosuna7824/nimbo/backend/internal/model"

func kubernetesGuide() Guide {
	return Guide{
		Platform:  "kubernetes",
		Name:      "Kubernetes",
		Framework: "Kubernetes configuration and security best practices",
		Sources: []Source{
			{"Kubernetes configuration best practices", "https://kubernetes.io/docs/concepts/configuration/overview/"},
			{"Kubernetes security", "https://kubernetes.io/docs/concepts/security/"},
			{"Kubernetes Pod Security Standards", "https://kubernetes.io/docs/concepts/security/pod-security-standards/"},
			{"Kubernetes Pod Security Admission", "https://kubernetes.io/docs/concepts/security/pod-security-admission/"},
			{"OWASP API Security Top 10 2023", "https://owasp.org/API-Security/editions/2023/en/0x11-t10"},
		},
		Pillars: []PillarGuide{
			pillar(model.PillarSecurity,
				"Restricted pod security, default-deny networking, least-privilege RBAC and real Secrets.",
				p("Apply a restricted securityContext",
					"Root, privileged or capability-rich containers make escapes trivial.",
					[]string{
						"Set runAsNonRoot: true, allowPrivilegeEscalation: false, readOnlyRootFilesystem: true.",
						"Set capabilities.drop: [ALL] and seccompProfile.type: RuntimeDefault.",
						"Never set privileged: true or hostNetwork/hostPID/hostIPC.",
					},
					"k8s_run_as_root", "k8s_capabilities", "k8s_seccomp", "k8s_privileged", "k8s_host_namespaces", "k8s_net_raw", "k8s_hardening"),
				p("Default-deny NetworkPolicies",
					"Without policies every pod can talk to every other pod.",
					[]string{"Add a NetworkPolicy with podSelector: {} and policyTypes [Ingress, Egress] per namespace, then allow specific flows (k3s enforces NetworkPolicy by default)."},
					"k8s_network_policy"),
				p("Grant least-privilege RBAC",
					"Wildcards, secrets access or cluster-admin bindings enable cluster takeover.",
					[]string{"Use namespaced Role/RoleBinding with explicit verbs/resources; dedicated ServiceAccounts with automountServiceAccountToken: false when unused."},
					"k8s_rbac_wildcard", "k8s_rbac_cluster_admin", "k8s_rbac_secrets", "k8s_rbac_default_sa", "k8s_automount_token", "k8s_rbac_escalate"),
				p("Store credentials in Secrets, not ConfigMaps or literals",
					"ConfigMaps and inline env values are readable by anyone with view access.",
					[]string{"Create a Secret and reference it with envFrom.secretRef / valueFrom.secretKeyRef or a volume mount."},
					"k8s_secret_in_configmap", "k8s_secret_env"),
				p("Avoid hostPath and hostPort",
					"Host mounts and ports break isolation between pods and node.",
					[]string{"Use PersistentVolumeClaims and Services instead."},
					"k8s_host_path", "k8s_host_port"),
				p("Rate limit and TLS-terminate public Ingresses",
					"An Ingress without TLS or request limits is the cluster's unprotected front door (OWASP API4:2023).",
					[]string{
						"Set spec.tls with a Secret on every Ingress with hosts; TLS 1.2+ at the controller.",
						"Rate limit at the controller: Traefik (k3s default) a rateLimit Middleware referenced by the traefik.ingress.kubernetes.io/router.middlewares annotation; ingress-nginx nginx.ingress.kubernetes.io/limit-rps.",
						"Label app namespaces pod-security.kubernetes.io/enforce: restricted (baseline when the workload needs it). Skip rate limits for cluster-internal Services.",
					},
					"k8s_ingress_tls", "k8s_pss_namespace_label"),
			),
			pillar(model.PillarReliability,
				"Probes, multiple replicas spread across nodes, disruption budgets and safe rollouts.",
				p("Configure readiness, liveness and startup probes",
					"Probes keep traffic off unready pods and restart hung ones.",
					[]string{"Add readinessProbe and livenessProbe (and startupProbe for slow starters) on a real container port."},
					"k8s_no_readiness_probe", "k8s_no_liveness_probe", "k8s_probe_port", "k8s_startup_probe"),
				p("Run ≥2 replicas with a PodDisruptionBudget (production)",
					"A single replica means downtime on every restart or node drain. On a single-node k3s sandbox this is optional.",
					[]string{"Set spec.replicas: 2+ and a PodDisruptionBudget with minAvailable: 1."},
					"k8s_single_replica", "k8s_pdb"),
				p("Spread replicas across nodes and zones (production)",
					"Replicas on one node fail together; irrelevant on single-node k3s.",
					[]string{"Add topologySpreadConstraints on kubernetes.io/hostname and topology.kubernetes.io/zone."},
					"k8s_topology_spread"),
				p("Use rolling updates with surge",
					"Safe rollouts avoid taking all replicas down at once.",
					[]string{"Set strategy.type: RollingUpdate with maxUnavailable: 0 and maxSurge: 1 on Deployments."},
					"k8s_rollout_strategy"),
				p("Use stable storage classes for state",
					"PVCs need a storage class that exists in the cluster (k3s ships local-path).",
					[]string{"Set storageClassName on PersistentVolumeClaims; use StatefulSets for databases."},
					"k8s_pvc_storage_class"),
			),
			pillar(model.PillarPerformance,
				"Requests and limits for scheduling, autoscaling on real metrics.",
				p("Set resource requests and memory limits",
					"Requests drive scheduling; limits stop noisy neighbours.",
					[]string{"Set resources.requests.cpu/memory and resources.limits.memory on every container."},
					"k8s_no_requests", "k8s_no_memory_limit"),
				p("Autoscale with HorizontalPodAutoscaler, within bounds",
					"HPA adds replicas under load; it needs CPU/memory requests to compute utilisation, and maxReplicas bounds a spike's cost.",
					[]string{"Create an autoscaling/v2 HorizontalPodAutoscaler with minReplicas (≥2 in production) and maxReplicas and averageUtilization targets (k3s ships metrics-server); add it in the prod overlay, not dev."},
					"k8s_hpa_no_requests"),
				p("Bound namespaces with quotas",
					"Quotas prevent one namespace exhausting the cluster.",
					[]string{"Add ResourceQuota and LimitRange per namespace."},
					"k8s_resource_quota"),
				p("Route traffic through Services and Ingress",
					"Services load-balance across ready pods; Ingress terminates HTTP centrally.",
					[]string{"Ensure Service selectors and targetPorts match pods and Ingress backends reference existing Services."},
					"k8s_service_port", "k8s_ingress_backend", "k8s_selector_mismatch"),
			),
			pillar(model.PillarCost,
				"Right-size requests, scale down when idle and keep quotas in place.",
				p("Right-size requests from observed usage",
					"Over-requested pods reserve capacity nobody uses.",
					[]string{"Start with modest requests, observe with metrics-server (kubectl top) and tune."},
					"k8s_no_requests"),
				p("Scale replicas with demand",
					"HPA scales in when load drops.",
					[]string{"Set HPA minReplicas low for non-critical workloads."},
					"k8s_hpa_no_requests"),
				p("Cap namespace consumption",
					"Quotas stop accidental runaway deployments.",
					[]string{"Apply ResourceQuota on requests.cpu, requests.memory and persistentvolumeclaims."},
					"k8s_resource_quota"),
				p("Use local images in the sandbox",
					"Pulling large remote images repeatedly wastes bandwidth and disk on a single node.",
					[]string{"Import locally built images into k3s and set imagePullPolicy: IfNotPresent."},
					"k8s_local_image"),
			),
			pillar(model.PillarOperations,
				"Pinned images, recommended labels, namespaces and current APIs.",
				p("Pin images by tag or digest",
					":latest makes rollouts non-reproducible.",
					[]string{"Use explicit tags (nginx:1.27.2) or @sha256 digests in production."},
					"k8s_latest_tag", "k8s_image_digest"),
				p("Apply recommended labels",
					"Standard labels make tooling, selectors and dashboards work.",
					[]string{"Set app.kubernetes.io/name, instance, version, component, part-of, managed-by."},
					"k8s_recommended_labels"),
				p("Use dedicated namespaces",
					"The default namespace mixes unrelated workloads and policies.",
					[]string{"Create a Namespace per app/environment and set metadata.namespace on every object."},
					"k8s_default_namespace", "k8s_namespace_missing"),
				p("Use current API versions",
					"Deprecated/removed APIs fail on cluster upgrades.",
					[]string{"Migrate manifests to the stable apiVersion (apps/v1, networking.k8s.io/v1, autoscaling/v2, policy/v1)."},
					"k8s_deprecated_api", "k8s_removed_api"),
			),
		},
	}
}
