package access

import (
	"slices"
	"strconv"
	"strings"

	"github.com/hashicorp/hcl/v2"
	"github.com/hashicorp/hcl/v2/hclsyntax"

	"github.com/ismaelosuna7824/nimbo/backend/internal/model"
)

// data "aws_iam_policy_document": statement blocks (sid, effect, actions,
// resources, principals blocks). condition / not_* attributes and blocks
// are kept as read-only extras; dynamic "statement" blocks are read-only
// statements.

func awsIsStmtBlock(b *model.Block) bool {
	return b.Type == "statement" || b.Type == "dynamic" && len(b.Labels) == 1 && b.Labels[0] == "statement"
}

func awsParseDocument(n *model.Node, s awsDocSpec) *awsParsed {
	p := &awsParsed{doc: model.AWSPolicyDocument{Path: s.path, Label: s.label, Encoding: "document", Editable: true, Statements: []model.AWSStatement{}}}
	if a := GetAttr(&n.Body, "version"); a != nil {
		if v, ok := awsConstStringSrc(Source(a.Value)); ok {
			p.doc.Version = v
		}
	}
	for i := range n.Body.Blocks {
		if b := &n.Body.Blocks[i]; awsIsStmtBlock(b) {
			p.add(awsParseDocStmt(b))
		}
	}
	return p
}

// awsRenderBlock renders a block as HCL (display and statement identity).
func awsRenderBlock(b *model.Block, ind string) string {
	var sb strings.Builder
	sb.WriteString(b.Type)
	for _, l := range b.Labels {
		sb.WriteString(" " + strconv.Quote(l))
	}
	sb.WriteString(" {\n")
	for _, a := range b.Body.Attrs {
		sb.WriteString(ind + "  " + a.Name + " = " + strings.TrimSpace(Source(a.Value)) + "\n")
	}
	for i := range b.Body.Blocks {
		sb.WriteString(ind + "  " + awsRenderBlock(&b.Body.Blocks[i], ind+"  ") + "\n")
	}
	sb.WriteString(ind + "}")
	return sb.String()
}

func awsParseDocStmt(b *model.Block) awsStmt {
	s := awsStmt{block: b, st: model.AWSStatement{Editable: true, Source: awsRenderBlock(b, ""), Effect: "Allow", Actions: []string{}, Resources: []string{}}}
	ro := func(reason string) {
		s.st.Editable = false
		if s.st.Reason == "" {
			s.st.Reason = reason
		}
	}
	if b.Type == "dynamic" {
		ro("This statement is generated by a dynamic block.")
		return s
	}
	for _, a := range b.Body.Attrs {
		src := strings.TrimSpace(Source(a.Value))
		e, diags := hclsyntax.ParseExpression([]byte(src+"\n"), a.Name, hcl.InitialPos)
		if diags.HasErrors() {
			ro(a.Name + " is not a valid expression.")
			s.st.Extra = append(s.st.Extra, model.AccessExtra{Key: a.Name, Source: src})
			continue
		}
		if awsDynamic(e) {
			ro("This statement uses a for expression or a conditional.")
		}
		switch a.Name {
		case "sid", "effect":
			str, ok := awsConstString(e)
			if !ok {
				ro(a.Name + " is computed.")
			}
			if a.Name == "sid" {
				s.st.Sid = str
			} else {
				s.st.Effect = str
			}
		case "actions":
			ss, ok := awsConstStrings(e)
			if !ok {
				ro("actions is computed.")
				ss = []string{}
			}
			s.st.Actions = ss
		case "resources":
			s.st.Resources = awsExprList(src, e)
		default:
			s.st.Extra = append(s.st.Extra, model.AccessExtra{Key: a.Name, Source: src})
		}
	}
	for i := range b.Body.Blocks {
		blk := &b.Body.Blocks[i]
		if blk.Type == "principals" {
			if pr, ok := awsDocPrincipal(blk); ok {
				s.st.Principals = append(s.st.Principals, pr)
				continue
			}
			ro("A principals block is computed.")
		}
		key := blk.Type
		if len(blk.Labels) > 0 {
			key += " " + strings.Join(blk.Labels, " ")
		}
		s.st.Extra = append(s.st.Extra, model.AccessExtra{Key: key, Source: awsRenderBlock(blk, "")})
	}
	return s
}

func awsDocPrincipal(b *model.Block) (model.AWSPrincipal, bool) {
	if len(b.Body.Blocks) > 0 || len(b.Body.Attrs) != 2 {
		return model.AWSPrincipal{}, false
	}
	var pr model.AWSPrincipal
	for _, a := range b.Body.Attrs {
		src := strings.TrimSpace(Source(a.Value))
		e, diags := hclsyntax.ParseExpression([]byte(src+"\n"), a.Name, hcl.InitialPos)
		if diags.HasErrors() || awsDynamic(e) {
			return model.AWSPrincipal{}, false
		}
		switch a.Name {
		case "type":
			t, ok := awsConstString(e)
			if !ok {
				return model.AWSPrincipal{}, false
			}
			pr.Type = t
		case "identifiers":
			pr.Values = awsExprList(src, e)
		default:
			return model.AWSPrincipal{}, false
		}
	}
	return pr, pr.Type != "" && pr.Values != nil
}

func awsCloneBody(b model.Body) model.Body {
	out := model.Body{Attrs: slices.Clone(b.Attrs), Blocks: make([]model.Block, len(b.Blocks)), Comments: b.Comments}
	if out.Attrs == nil {
		out.Attrs = []model.Attr{}
	}
	for i, blk := range b.Blocks {
		out.Blocks[i] = model.Block{Type: blk.Type, Labels: slices.Clone(blk.Labels), Body: awsCloneBody(blk.Body), File: blk.File, Order: blk.Order}
	}
	return out
}

func awsWriteDocument(n *model.Node, p *awsParsed, doc model.AWSPolicyDocument, idx []int) error {
	stmts := make([]model.Block, 0, len(doc.Statements))
	for i, st := range doc.Statements {
		j := idx[i]
		if j >= 0 && awsSameStmt(st, p.stmts[j].st) {
			stmts = append(stmts, *p.stmts[j].block)
			continue
		}
		if err := awsValidate(i, st); err != nil {
			return err
		}
		orig := model.AWSStatement{Effect: "Allow"}
		b := model.Block{Type: "statement", Body: model.Body{Attrs: []model.Attr{}, Blocks: []model.Block{}}}
		if j >= 0 {
			orig = p.stmts[j].st
			b = model.Block{Type: "statement", Labels: slices.Clone(p.stmts[j].block.Labels), Body: awsCloneBody(p.stmts[j].block.Body)}
			if !awsSameExtras(st.Extra, orig.Extra) {
				return Editf("access: statement %d: conditions and other extra keys of a policy document are read-only here; edit them in code", i+1)
			}
		} else if len(st.Extra) > 0 {
			return Editf("access: statement %d: conditions and other extra keys can only be added to a policy document in code", i+1)
		}
		if j < 0 || st.Sid != orig.Sid {
			if st.Sid == "" {
				Unset(&b.Body, "sid")
			} else {
				SetExpr(&b.Body, "sid", awsQuote(st.Sid))
			}
		}
		if j < 0 || st.Effect != orig.Effect {
			SetExpr(&b.Body, "effect", awsQuote(st.Effect))
		}
		if j < 0 || !slices.Equal(st.Actions, orig.Actions) {
			if len(st.Actions) == 0 {
				Unset(&b.Body, "actions")
			} else {
				SetExpr(&b.Body, "actions", awsHCLList(awsHCLQuoted(st.Actions)))
			}
		}
		if j < 0 || !awsSameExprs(st.Resources, orig.Resources) {
			if len(st.Resources) == 0 {
				Unset(&b.Body, "resources")
			} else {
				SetExpr(&b.Body, "resources", awsHCLList(awsTrimmed(st.Resources)))
			}
		}
		if j < 0 || !awsSamePrincipals(st.Principals, orig.Principals) {
			b.Body.Blocks = slices.DeleteFunc(b.Body.Blocks, func(x model.Block) bool { return x.Type == "principals" })
			for _, pr := range st.Principals {
				pb := model.Block{Type: "principals", Body: model.Body{Attrs: []model.Attr{}, Blocks: []model.Block{}}}
				SetExpr(&pb.Body, "type", awsQuote(pr.Type))
				SetExpr(&pb.Body, "identifiers", awsHCLList(awsTrimmed(pr.Values)))
				b.Body.Blocks = append(b.Body.Blocks, pb)
			}
		}
		stmts = append(stmts, b)
	}
	if doc.Version != "" && doc.Version != p.doc.Version {
		SetExpr(&n.Body, "version", awsQuote(doc.Version))
	}
	out := make([]model.Block, 0, len(n.Body.Blocks)+len(stmts))
	placed := false
	for i := range n.Body.Blocks {
		if awsIsStmtBlock(&n.Body.Blocks[i]) {
			if !placed {
				out = append(out, stmts...)
				placed = true
			}
			continue
		}
		out = append(out, n.Body.Blocks[i])
	}
	if !placed {
		out = append(out, stmts...)
	}
	n.Body.Blocks = out
	return nil
}
