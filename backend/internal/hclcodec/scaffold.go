// Project files generated next to the Terraform. Each starts with a marker
// line so a folder import of an export recognizes and skips them (they are
// regenerated); deleting the marker turns the file into the user's own.
const (
	ReadmeFile       = "README.md"
	GitignoreFile    = ".gitignore"
	TfvarsSampleFile = "terraform.tfvars.example"

	readmeMarker    = "<!-- Generated by Nimbo from the workflow: rewritten on every export. Delete this line to keep your own README. -->"
	gitignoreMarker = "# Generated by Nimbo: rewritten on every export. Delete this line to keep your own .gitignore."
	tfvarsMarker    = "# Generated by Nimbo from the workflow's variables: rewritten on every export. Delete this line to keep your own copy."
)

// Scaffold renders the project files of wf's layout (see ResolveLayout).
// Single layout: README.md (see Readme), .gitignore (Terraform working
// data, state, plans, crash logs, CLI configuration and variable files),
// terraform.tfvars.example (every variable, sensitive ones blank; omitted
// without variables) and backend.tf.example (a remote state backend for the
// workflow's cloud; omitted when it has a backend or no cloud).
// Environments layout: README.md (tree, usage, environments), .gitignore,
// Makefile, modules/<service>/README.md and, with the cloud's default
// backend, environments/<env>/backend.hcl.example. Callers skip names the
// workflow already has as its own files.
func Scaffold(wf *model.Workflow, resourceFile func(resourceType string) string) map[string][]byte {
	if layout, err := ResolveLayout(wf); err == nil && layout == model.LayoutEnvironments {
		if out, err := envScaffold(wf, resourceFile); err == nil {
			return out
		}
	}
	out := map[string][]byte{
		ReadmeFile:    Readme(wf, ReadmeOptions{ResourceFile: resourceFile}),
		GitignoreFile: []byte(gitignore),
	}
	if len(wf.Variables) > 0 {
		out[TfvarsSampleFile] = tfvarsSample(wf)
	}
	if data := backendTfExample(wf); data != nil {
		out[BackendTfExampleFile] = data
	}
	return out
}

// IsScaffold reports whether a project file is one Scaffold generated (its
// marker line is still there). name may be a path: the base name decides.
func IsScaffold(name string, content []byte) bool {
	marker := map[string]string{
		ReadmeFile: readmeMarker, GitignoreFile: gitignoreMarker, TfvarsSampleFile: tfvarsMarker,
		BackendTfExampleFile: backendExampleMarker, BackendExampleFile: backendExampleMarker, MakefileFile: makefileMarker,
	}[path.Base(name)]
	if marker == "" {
		return false
	}
	return bytes.HasPrefix(bytes.ReplaceAll(content, []byte("\r\n"), []byte("\n")), []byte(marker+"\n"))
}

// backendTfExample is a remote state backend for a single-layout workflow
// without one: the default of its cloud (nil without a cloud), partial so
// the storage location stays out of the code.
func backendTfExample(wf *model.Workflow) []byte {
	if HasBackend(wf) {
		return nil
	}
	plan := defaultBackend(primaryCloud(wf), ServiceName(wf))
	if plan == nil {
		return nil
	}
	blk := cloneBlock(plan.block)
	setAttr(&blk.Body, plan.key.attr, stringValue(plan.base), true)
	lead := []string{
		backendExampleMarker,
		"# Remote state: copy this file to backend.tf, put the storage settings in",
		"# backend.hcl and run terraform init -backend-config=backend.hcl. backend.hcl:",
	}
	for _, l := range plan.example {
		lead = append(lead, "#   "+l)
	}
	w := &writer{}
	w.block("terraform", "terraform", nil, &model.Body{Attrs: []model.Attr{}, Blocks: []model.Block{blk}, Comments: &model.Comments{Lead: lead}})
	if w.err != nil {
		return nil
	}
	out, err := formatFile(BackendTfExampleFile, w.buf.String())
	if err != nil {
		return nil
	}
	return out
}

