// ReadmeOptions tunes Readme.
type ReadmeOptions struct {
	// ResourceFile is ExportOptions.ResourceFile (the File column of the
	// resources table).
	ResourceFile func(resourceType string) string
	// ModuleSource, when set, documents a reusable module: the usage section
	// shows a module call with this source and the required inputs.
	ModuleSource string
}

// Readme renders terraform-docs-style documentation of wf: the workflow
// description, usage, requirements, providers, module calls, resources (with
// their file), inputs (name, description, type, default, required) and
// outputs. Deterministic: the same workflow gives the same bytes.
func Readme(wf *model.Workflow, opts ReadmeOptions) []byte {
	var b strings.Builder
	line := func(s ...string) {
		for _, l := range s {
			b.WriteString(l)
			b.WriteByte('\n')
		}
	}
	title := strings.TrimSpace(wf.Name)
	if title == "" {
		title = "Terraform configuration"
	}
	line(readmeMarker, "", "# "+mdText(title), "")
	if d := strings.TrimSpace(wf.Description); d != "" {
		line(d, "")
	}

	line("## Usage", "")
	if opts.ModuleSource != "" {
		args := [][2]string{{"source", fmt.Sprintf("%q", opts.ModuleSource)}}
		for i := range wf.Variables {
			if v := &wf.Variables[i]; required(&v.Body) {
				args = append(args, [2]string{v.Name, placeholder(&v.Body)})
			}
		}
		width := 0
		for _, a := range args {
			width = max(width, len(a[0]))
		}
		// Aligned the way terraform fmt writes it.
		line("```hcl", fmt.Sprintf("module %q {", moduleLabel(title)))
		for _, a := range args {
			line(fmt.Sprintf("  %-*s = %s", width, a[0], a[1]))
		}
		line("}", "```", "")
	} else {
		line("```sh", "terraform init", "terraform plan -out=tfplan", "terraform apply tfplan", "```", "")
		if len(wf.Variables) > 0 {
			line("Set the inputs below: copy `terraform.tfvars.example` to `terraform.tfvars` and fill it in, or pass `-var-file=<file>`.")
			var envs []string
			for _, e := range wf.Environments {
				if e.File == "" {
					envs = append(envs, "`-var-file=environments/"+e.Name+".tfvars`")
				}
			}
			if len(envs) > 0 {
				line("Environments: " + strings.Join(envs, ", ") + ".")
			}
			line("")
		}
		stateSection(wf, line)
	}

	// Requirements and providers come from the terraform block.
	version, providers := requirements(wf)
	line("## Requirements", "", "| Name | Version |", "|------|---------|")
	if version == "" {
		version = "n/a"
	} else {
		version = code(version)
	}
	line("| terraform | " + version + " |")
	for _, p := range providers {
		line("| " + p.name + " | " + orNA(p.version) + " |")
	}
	line("")
	if len(providers) > 0 {
		line("## Providers", "", "| Name | Source | Version |", "|------|--------|---------|")
		for _, p := range providers {
			line("| " + p.name + " | " + orNA(p.source) + " | " + orNA(p.version) + " |")
		}
		line("")
	}

	files := Layout(wf, opts.ResourceFile).Nodes
	var modules, resources []int
	for i := range wf.Nodes {
		if wf.Nodes[i].Kind == model.KindModule {
			modules = append(modules, i)
		} else {
			resources = append(resources, i)
		}
	}
	byAddress := func(a, b int) int { return strings.Compare(Address(&wf.Nodes[a]), Address(&wf.Nodes[b])) }
	if len(modules) > 0 {
		slices.SortFunc(modules, byAddress)
		line("## Modules", "", "| Name | Source | Version | File |", "|------|--------|---------|------|")
		for _, i := range modules {
			n := &wf.Nodes[i]
			line("| " + n.Name + " | " + orNA(attrText(&n.Body, "source")) + " | " + orNA(attrText(&n.Body, "version")) + " | " + files[i] + " |")
		}
		line("")
	}
	line("## Resources", "")
	if len(resources) == 0 {
		line("No resources.", "")
	} else {
		slices.SortFunc(resources, byAddress)
		line("| Name | Type | File |", "|------|------|------|")
		for _, i := range resources {
			n := &wf.Nodes[i]
			kind := "resource"
			if n.Kind == model.KindData {
				kind = "data source"
			}
			line("| " + code(Address(n)) + " | " + kind + " | " + files[i] + " |")
		}
		line("")
	}

	line("## Inputs", "")
	if len(wf.Variables) == 0 {
		line("No inputs.", "")
	} else {
		vars := slices.Clone(wf.Variables)
		slices.SortStableFunc(vars, func(a, b model.NamedBlock) int { return strings.Compare(a.Name, b.Name) })
		line("| Name | Description | Type | Default | Required |", "|------|-------------|------|---------|:--------:|")
		for i := range vars {
			v := &vars[i]
			typ, def := orNA(code(attrExpr(&v.Body, "type"))), "n/a"
			if d := attrExpr(&v.Body, "default"); d != "" {
				def = code(d)
				if isTrue(&v.Body, "sensitive") {
					def = "(sensitive)"
				}
			}
			req := "no"
			if required(&v.Body) {
				req = "yes"
			}
			line("| " + v.Name + " | " + orNA(mdText(attrText(&v.Body, "description"))) + " | " + typ + " | " + def + " | " + req + " |")
		}
		line("")
	}

	line("## Outputs", "")
	if len(wf.Outputs) == 0 {
		line("No outputs.")
	} else {
		outs := slices.Clone(wf.Outputs)
		slices.SortStableFunc(outs, func(a, b model.NamedBlock) int { return strings.Compare(a.Name, b.Name) })
		line("| Name | Description | Sensitive |", "|------|-------------|:---------:|")
		for i := range outs {
			o := &outs[i]
			sens := "no"
			if isTrue(&o.Body, "sensitive") {
				sens = "yes"
			}
			line("| " + o.Name + " | " + orNA(mdText(attrText(&o.Body, "description"))) + " | " + sens + " |")
		}
	}
	return []byte(b.String())
}

type providerReq struct{ name, source, version string }

// requirements reads required_version and required_providers of the
// terraform block (and of provider blocks without an entry).
func requirements(wf *model.Workflow) (version string, providers []providerReq) {
	seen := map[string]bool{}
	if wf.Terraform != nil {
		version = attrText(wf.Terraform, "required_version")
		for i := range wf.Terraform.Blocks {
			blk := &wf.Terraform.Blocks[i]
			if blk.Type != "required_providers" {
				continue
			}
			for _, a := range blk.Body.Attrs {
				if seen[a.Name] {
					continue
				}
				seen[a.Name] = true
				source, constraint := requiredProvider(wf, a.Name)
				p := providerReq{name: a.Name, source: exprText(source)}
				if constraint != "" {
					p.version = code(exprText(constraint))
				}
				providers = append(providers, p)
			}
		}
	}
	for _, p := range wf.Providers {
		if !seen[p.Name] {
			seen[p.Name] = true
			providers = append(providers, providerReq{name: p.Name})
		}
	}
	slices.SortFunc(providers, func(a, b providerReq) int { return strings.Compare(a.name, b.name) })
	return version, providers
}

// exprText is the value of a constant string expression, else the
// expression itself.
func exprText(expr string) string {
	var s string
	if lit, ok := LiteralFromExpr(expr); ok && json.Unmarshal(lit, &s) == nil {
		return s
	}
	return expr
}

// tfvarsSample lists every variable with its description, its default
// (blank when sensitive) or a placeholder of its type.
func tfvarsSample(wf *model.Workflow) []byte {
	var b strings.Builder
	b.WriteString(tfvarsMarker + "\n# Copy to terraform.tfvars and set the values; required inputs are marked.\n")
	for i := range wf.Variables {
		v := &wf.Variables[i]
		b.WriteByte('\n')
		desc := attrText(&v.Body, "description")
		if required(&v.Body) {
			desc = strings.TrimSpace(desc + " (required)")
		}
		for _, l := range strings.Split(desc, "\n") {
			if l = strings.TrimRight(l, " \t\r"); l != "" {
				b.WriteString("# " + l + "\n")
			}
		}
		value := placeholder(&v.Body)
		if d := attrExpr(&v.Body, "default"); d != "" && !isTrue(&v.Body, "sensitive") {
			value = d
		}
		b.WriteString(v.Name + " = " + value + "\n")
	}
	return hclwrite.Format([]byte(b.String()))
}

// placeholder is an empty value of a variable's type.
func placeholder(body *model.Body) string {
	t := strings.TrimSpace(attrExpr(body, "type"))
	switch {
	case t == "number":
		return "0"
	case t == "bool":
		return "false"
	case strings.HasPrefix(t, "list"), strings.HasPrefix(t, "set"), strings.HasPrefix(t, "tuple"):
		return "[]"
	case strings.HasPrefix(t, "map"), strings.HasPrefix(t, "object"):
		return "{}"
	}
	return `""`
}

// required reports a variable without a default.
func required(body *model.Body) bool {
	for _, a := range body.Attrs {
		if a.Name == "default" {
			return false
		}
	}
	return true
}

func attrExpr(body *model.Body, name string) string {
	for _, a := range body.Attrs {
		if a.Name == name {
			if expr, err := exprOf(a.Value); err == nil {
				return expr
			}
			return strings.TrimSpace(a.Value.Expr)
		}
	}
	return ""
}

// attrText is a string attribute's value, or its expression when it is
// not a constant string.
func attrText(body *model.Body, name string) string {
	for _, a := range body.Attrs {
		if a.Name != name {
			continue
		}
		var s string
		lit := a.Value.Literal
		if len(lit) == 0 {
			lit, _ = LiteralFromExpr(a.Value.Expr)
		}
		if json.Unmarshal(lit, &s) == nil {
			return s
		}
		return attrExpr(body, name)
	}
	return ""
}

func isTrue(body *model.Body, name string) bool {
	return attrExpr(body, name) == "true"
}

// code renders an expression in a table cell: one line, in backticks.
func code(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if s == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(s, "|", `\|`) + "`"
}

// mdText renders plain text in a table cell or heading.
func mdText(s string) string {
	s = strings.TrimSpace(s)
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\r\n", "\n")
	return strings.ReplaceAll(s, "\n", "<br>")
}

func orNA(s string) string {
	if s == "" {
		return "n/a"
	}
	return s
}

// moduleLabel turns a title into a module call label.
func moduleLabel(title string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(title) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '_':
			b.WriteRune(r)
		case b.Len() > 0 && !strings.HasSuffix(b.String(), "_"):
			b.WriteByte('_')
		}
	}
	s := strings.Trim(b.String(), "_")
	if s == "" || s[0] >= '0' && s[0] <= '9' {
		s = "this"
	}
	return s
}

// stateSection documents where a single-layout root keeps its state and
// that its environments share it.
func stateSection(wf *model.Workflow, line func(s ...string)) {
	line("## State & environments", "")
	kind := ""
	if wf.Terraform != nil {
		for _, b := range wf.Terraform.Blocks {
			switch {
			case b.Type == "cloud":
				kind = "HCP Terraform (`cloud` block)"
			case b.Type == "backend" && len(b.Labels) == 1:
				kind = "the `" + b.Labels[0] + "` backend"
			}
		}
	}
	switch {
	case kind != "":
		line("This is one root module with one state, kept in " + kind + ".")
	case backendTfExample(wf) != nil:
		line("This is one root module with one state, kept in a local `terraform.tfstate` file. For a shared remote state with locking, copy `" +
			BackendTfExampleFile + "` to `backend.tf` and follow its comments.")
	default:
		line("This is one root module with one state, kept in a local `terraform.tfstate` file.")
	}
	if len(wf.Environments) > 1 {
		line("", "Its environments are variable files of this one root, so they share that state: applying one environment replaces what another one created. "+
			"Before deploying more than one, give each its own state: export with the environments layout (one root module, and one state, per environment), "+
			"or initialize each environment with its own state key (`terraform init -reconfigure -backend-config=\"key=<env>/terraform.tfstate\"`).")
	}
	line("")
}
