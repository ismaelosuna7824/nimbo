// The environments layout (model.LayoutEnvironments): the workflow's
// Terraform becomes one service module and every environment gets its own
// root module, so its own state:
//
//	modules/<service>/        the workflow's blocks without provider configuration
//	modules/<name>/           the local modules it calls (workflow assets)
//	environments/<env>/       backend.tf, versions.tf, providers.tf, variables.tf,
//	                          locals.tf, main.tf (calls the service module),
//	                          outputs.tf, terraform.tfvars, .env.example
//
// Variables whose effective value differs between environments lose their
// default in the service module (the environments must set them); the
// others keep it. A root passes every input some environment sets (a value
// or a TF_VAR_<name> environment variable) and every input without a
// default. Values of sensitive variables are never written: each
// .env.example lists them as TF_VAR_<name>. Provider configuration, and the
// variables and locals it reads, live in every root; `import` and `removed`
// blocks too (their addresses gain the module.<service>. prefix), since
// Terraform only accepts them in a root module.

const (
	// EnvironmentsDir holds one root module per environment.
	EnvironmentsDir = "environments"
	// ModulesDir holds the service module and the local modules.
	ModulesDir = "modules"
	// MakefileFile and BackendExampleFile are scaffold of the environments
	// layout (the latter in every environment root).
	MakefileFile       = "Makefile"
	BackendExampleFile = "backend.hcl.example"
	// BackendTfExampleFile is the backend scaffold of the single layout.
	BackendTfExampleFile = "backend.tf.example"

	// defaultEnvironment names the only root of a workflow without
	// environments.
	defaultEnvironment = "default"

	makefileMarker       = "# Generated by Nimbo: rewritten on every export. Delete this line to keep your own Makefile."
	backendExampleMarker = "# Generated by Nimbo: rewritten on every export. Delete this line to keep your own copy."
)

// envNameRe is what an environment name must look like to name a directory
// (and a make variable value).
var envNameRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.-]*$`)

// EnvironmentNames lists the environment roots of the environments layout,
// sorted: the names of wf's environments, or "default" without any.
func EnvironmentNames(wf *model.Workflow) []string {
	if len(wf.Environments) == 0 {
		return []string{defaultEnvironment}
	}
	names := make([]string, 0, len(wf.Environments))
	for _, e := range wf.Environments {
		names = append(names, e.Name)
	}
	slices.Sort(names)
	return names
}

// serviceNameRe: a module call name that is also a directory name.
var serviceNameRe = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_-]*$`)

// ValidServiceName reports whether name can be model.Workflow.Service.
func ValidServiceName(name string) error {
	if !serviceNameRe.MatchString(name) {
		return fmt.Errorf("invalid service name %q: use letters, digits, '_' and '-', starting with a letter", name)
	}
	return nil
}

// ServiceName is the directory (modules/<name>) and module call name of the
// service module: model.Workflow.Service when set (and valid), else the
// workflow name in snake_case made unique against the local modules the
// workflow calls.
func ServiceName(wf *model.Workflow) string {
	if wf.Service != "" && ValidServiceName(wf.Service) == nil {
		return wf.Service
	}
	name := moduleLabel(wf.Name)
	taken := map[string]bool{}
	for i := range wf.Nodes {
		if dir, ok := LocalModuleDir(&wf.Nodes[i]); ok && path.Dir(dir) == ModulesDir {
			taken[path.Base(dir)] = true
		}
	}
	for taken[name] {
		name += "_service"
	}
	return name
}

// CheckEnvironmentsLayout reports why wf cannot be written in the
// environments layout: an environment name that cannot name a directory,
// or provider configuration (or a root-only block) that reads resources,
// data sources or modules, which live in the service module.
func CheckEnvironmentsLayout(wf *model.Workflow) error {
	seen := map[string]bool{}
	for _, e := range wf.Environments {
		if !envNameRe.MatchString(e.Name) {
			return fmt.Errorf("environment name %q cannot name a directory: use letters, digits, '-', '_' and '.'", e.Name)
		}
		if seen[e.Name] {
			return fmt.Errorf("environment %q is defined twice", e.Name)
		}
		seen[e.Name] = true
	}
	_, _, err := rootReferences(wf)
	return err
}

// ResolveLayout returns the layout Export writes for wf: its effective
// layout (model.Workflow.EffectiveLayout), except that an automatic choice
// of the environments layout falls back to the single layout when
// CheckEnvironmentsLayout fails. A layout chosen explicitly fails instead.
func ResolveLayout(wf *model.Workflow) (string, error) {
	layout := wf.EffectiveLayout()
	if layout != model.LayoutEnvironments {
		return layout, nil
	}
	if err := CheckEnvironmentsLayout(wf); err != nil {
		if wf.Layout == model.LayoutAuto {
			return model.LayoutSingle, nil
		}
		return "", fmt.Errorf("environments layout: %w", err)
	}
	return layout, nil
}

// ExportLayout renders wf's Terraform in its layout (see ResolveLayout):
// Export for the single layout, ExportEnvironments for the environments
// layout.
func ExportLayout(wf *model.Workflow, opts ExportOptions) (map[string][]byte, error) {
	layout, err := ResolveLayout(wf)
	if err != nil {
		return nil, err
	}
	if layout == model.LayoutEnvironments {
		return ExportEnvironments(wf, opts)
	}
	return Export(wf, opts)
}

// AssetPlacement returns where an export of wf writes a workflow asset
// (slash path relative to the workflow files): the same path in the single
// layout. In the environments layout local modules (modules/...) stay, the
// dependency lock file goes to every environment root and every other
// asset moves into the service module, next to the blocks that read it
// through path.module.
func AssetPlacement(wf *model.Workflow) func(rel string) []string {
	layout, err := ResolveLayout(wf)
	if err != nil || layout != model.LayoutEnvironments {
		return func(rel string) []string { return []string{rel} }
	}
	svc, envs := ServiceName(wf), EnvironmentNames(wf)
	return func(rel string) []string {
		switch {
		case strings.HasPrefix(rel, ModulesDir+"/"):
			return []string{rel}
		case rel == ".terraform.lock.hcl":
			out := make([]string, len(envs))
			for i, e := range envs {
				out[i] = EnvironmentsDir + "/" + e + "/" + rel
			}
			return out
		}
		return []string{ModulesDir + "/" + svc + "/" + rel}
	}
}

