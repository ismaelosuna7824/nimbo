// moduleReferences returns the variables and locals the service module
// reads: from its resources, data sources, module calls, outputs and other
// blocks (root-only ones excluded), the locals those read (transitively)
// and the validations of the variables read so far (a variable's own
// validation does not make it read).
func moduleReferences(wf *model.Workflow) (vars, locals map[string]bool, err error) {
	vars, locals = map[string]bool{}, map[string]bool{}
	var queue []string
	visit := func(owner, expr string) error {
		e, err := parseExpr(expr)
		if err != nil {
			return fmt.Errorf("%s: %w", owner, err)
		}
		for _, tr := range e.Variables() {
			name, ok := attrStep(tr, 1)
			if !ok {
				continue
			}
			switch tr.RootName() {
			case "var":
				if !vars[name] {
					vars[name] = true
					queue = append(queue, "var."+name)
				}
			case "local":
				if !locals[name] {
					locals[name] = true
					queue = append(queue, "local."+name)
				}
			}
		}
		return nil
	}
	walk := func(owner string, b *model.Body) error {
		return walkExprs(b, nil, func(expr string) error { return visit(owner, expr) })
	}
	for i := range wf.Nodes {
		if err := walk(Address(&wf.Nodes[i]), &wf.Nodes[i].Body); err != nil {
			return nil, nil, err
		}
	}
	for i := range wf.Outputs {
		if err := walk("output "+wf.Outputs[i].Name, &wf.Outputs[i].Body); err != nil {
			return nil, nil, err
		}
	}
	for i := range wf.Other {
		if !rootOnlyBlock(wf.Other[i].Type) {
			if err := walk(wf.Other[i].Type+" block", &wf.Other[i].Body); err != nil {
				return nil, nil, err
			}
		}
	}
	for len(queue) > 0 {
		ref := queue[0]
		queue = queue[1:]
		kind, name, _ := strings.Cut(ref, ".")
		if kind == "local" {
			for _, a := range wf.Locals {
				if a.Name != name {
					continue
				}
				expr, err := exprOf(a.Value)
				if err != nil {
					return nil, nil, fmt.Errorf("local.%s: %w", name, err)
				}
				if err := visit("local."+name, expr); err != nil {
					return nil, nil, err
				}
			}
			continue
		}
		for i := range wf.Variables {
			v := &wf.Variables[i]
			if v.Name != name {
				continue
			}
			for j := range v.Body.Blocks {
				if err := walk("variable "+name, &v.Body.Blocks[j].Body); err != nil {
					return nil, nil, err
				}
			}
		}
	}
	return vars, locals, nil
}
