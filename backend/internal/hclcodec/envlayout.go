// layoutVar is one workflow variable in the environments layout.
type layoutVar struct {
	block *model.NamedBlock
	def   string // default expression ("" without one)
	// secret: sensitive, never written to a variable file. specific: the
	// effective value differs between environments. used: the service
	// module reads it (else it is not declared there). root: provider
	// configuration or a root-only block reads it (every root declares
	// it). passed: every root passes it to the service module.
	secret, specific, used, root, passed bool
}

// moduleDefault: the service module keeps the default. Only one place
// holds a default: an input the roots always pass (because they read it
// too) gets it from the root; an environment-specific one has none.
func (v layoutVar) moduleDefault() bool { return !v.specific && !(v.root && v.passed) }

// rootDeclared: the roots declare it; rootDefault: with its default.
func (v layoutVar) rootDeclared() bool { return v.passed || v.root }
func (v layoutVar) rootDefault() bool  { return v.root && !v.specific }

// envLayout is the environments layout of one workflow.
type envLayout struct {
	wf      *model.Workflow
	svc     string
	envs    []*model.Environment // by name; a synthetic "default" without environments
	vars    []layoutVar          // in workflow order
	rootVar map[string]bool      // read by provider configuration or root-only blocks
	locals  []model.Attr         // the locals those read, sorted by name
	// moduleLocals are the locals the service module reads.
	moduleLocals map[string]bool
	backend      *backendPlan
	cloud        model.Cloud
}

func newEnvLayout(wf *model.Workflow) (*envLayout, error) {
	if err := CheckEnvironmentsLayout(wf); err != nil {
		return nil, err
	}
	l := &envLayout{wf: wf, svc: ServiceName(wf)}
	for _, name := range EnvironmentNames(wf) {
		if i := envIndex(wf.Environments, name); i >= 0 {
			l.envs = append(l.envs, &wf.Environments[i])
		} else {
			l.envs = append(l.envs, &model.Environment{Name: name, Values: map[string]model.Value{}})
		}
	}
	var err error
	if l.rootVar, l.locals, err = rootReferences(wf); err != nil {
		return nil, err
	}
	slices.SortStableFunc(l.locals, func(a, b model.Attr) int { return strings.Compare(a.Name, b.Name) })
	var moduleVars map[string]bool
	if moduleVars, l.moduleLocals, err = moduleReferences(wf); err != nil {
		return nil, err
	}
	for i := range wf.Variables {
		v := &wf.Variables[i]
		lv := layoutVar{block: v, def: attrExpr(&v.Body, "default"), secret: isTrue(&v.Body, "sensitive"),
			used: moduleVars[v.Name], root: l.rootVar[v.Name]}
		set := false
		var first string
		for j, e := range l.envs {
			eff := "\x00unset"
			if lv.def != "" {
				eff = canonExpr(lv.def)
			}
			if val, ok := e.Values[v.Name]; ok {
				expr, err := exprOf(val)
				if err != nil {
					return nil, fmt.Errorf("environment %s: %s: %w", e.Name, v.Name, err)
				}
				eff, set = canonExpr(expr), true
			} else if hasEnvVar(e, "TF_VAR_"+v.Name) {
				eff, set = "\x00env", true
			}
			if j == 0 {
				first = eff
			} else if eff != first {
				lv.specific = true
			}
		}
		lv.passed = lv.used && (set || lv.specific || lv.def == "" || lv.root)
		l.vars = append(l.vars, lv)
	}
	l.cloud = primaryCloud(wf)
	l.backend = newBackendPlan(wf, l.cloud, l.svc)
	return l, nil
}

func hasEnvVar(e *model.Environment, key string) bool {
	for _, v := range e.EnvVars {
		if v.Key == key {
			return true
		}
	}
	return false
}

// canonExpr formats an expression so equal values compare equal.
func canonExpr(expr string) string {
	return strings.TrimSpace(string(hclwrite.Format([]byte("x = " + strings.TrimSpace(expr) + "\n"))))
}

// primaryCloud is the cloud whose state backend the roots use: the first
// cloud of the workflow in model.AllClouds order ("" without one).
func primaryCloud(wf *model.Workflow) model.Cloud {
	if clouds := cloudsOf(wf); len(clouds) > 0 {
		return clouds[0]
	}
	return ""
}

// rootReferences returns the variables and locals (with every local they
// read, in workflow order) that provider configuration and root-only blocks
// (import, removed) read: they are declared in every root too. Reading a
// resource, data source or module fails: those live in the service module.
func rootReferences(wf *model.Workflow) (vars map[string]bool, locals []model.Attr, err error) {
	types := map[string]bool{}
	for i := range wf.Nodes {
		types[wf.Nodes[i].Type] = true
	}
	vars = map[string]bool{}
	wantLocal := map[string]bool{}
	var queue []string
	visit := func(owner, expr string) error {
		e, err := parseExpr(expr)
		if err != nil {
			return fmt.Errorf("%s: %w", owner, err)
		}
		for _, tr := range e.Variables() {
			root := tr.RootName()
			switch {
			case root == "var" || root == "local":
				name, ok := attrStep(tr, 1)
				if !ok {
					continue
				}
				if root == "var" {
					vars[name] = true
				} else if !wantLocal[name] {
					wantLocal[name] = true
					queue = append(queue, name)
				}
			case root == "data" || root == "module" || types[root]:
				ref := root
				if next, ok := attrStep(tr, 1); ok {
					ref += "." + next
				}
				return fmt.Errorf("%s reads %s; in the environments layout it moves to every environment root, where only variables and locals are available", owner, ref)
			}
		}
		return nil
	}
	for i := range wf.Providers {
		p := &wf.Providers[i]
		if err := walkExprs(&p.Body, nil, func(expr string) error { return visit("provider "+p.Name, expr) }); err != nil {
			return nil, nil, err
		}
	}
	for i := range wf.Other {
		b := &wf.Other[i]
		if !rootOnlyBlock(b.Type) {
			continue
		}
		skip := map[string]bool{"to": true, "from": true}
		if err := walkExprs(&b.Body, skip, func(expr string) error { return visit(b.Type+" block", expr) }); err != nil {
			return nil, nil, err
		}
	}
	for len(queue) > 0 {
		name := queue[0]
		queue = queue[1:]
		for _, a := range wf.Locals {
			if a.Name != name {
				continue
			}
			expr, err := exprOf(a.Value)
			if err != nil {
				return nil, nil, fmt.Errorf("local.%s: %w", name, err)
			}
			if err := visit("local."+name+" (read by provider configuration)", expr); err != nil {
				return nil, nil, err
			}
		}
	}
	for _, a := range wf.Locals {
		if wantLocal[a.Name] {
			locals = append(locals, a)
		}
	}
	return vars, locals, nil
}

// rootOnlyBlock reports top-level blocks Terraform only accepts in a root
// module.
func rootOnlyBlock(typ string) bool {
	return typ == "import" || typ == "removed"
}

// walkExprs calls fn with every attribute expression of b and its nested
// blocks, except top-level attributes named in skip.
func walkExprs(b *model.Body, skip map[string]bool, fn func(expr string) error) error {
	for _, a := range b.Attrs {
		if skip[a.Name] {
			continue
		}
		expr, err := exprOf(a.Value)
		if err != nil {
			return fmt.Errorf("%s: %w", a.Name, err)
		}
		if err := fn(expr); err != nil {
			return err
		}
	}
	for i := range b.Blocks {
		if err := walkExprs(&b.Blocks[i].Body, nil, fn); err != nil {
			return err
		}
	}
	return nil
}

