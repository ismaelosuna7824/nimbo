// Versions

var versionRe = regexp.MustCompile(`\d+(?:\.\d+)*`)

// minimumConstraint turns a root's constraint ("~> 6.0") into the minimum a
// reusable module declares (">= 6.0"); "" when it names no version.
func minimumConstraint(constraint string) string {
	for _, part := range strings.Split(constraint, ",") {
		part = strings.TrimSpace(part)
		if strings.HasPrefix(part, "!=") || strings.HasPrefix(part, "<") {
			continue
		}
		if v := versionRe.FindString(part); v != "" {
			return ">= " + v
		}
	}
	return ""
}

// compareVersions compares dotted versions numerically.
func compareVersions(a, b string) int {
	pa, pb := strings.Split(a, "."), strings.Split(b, ".")
	for i := range max(len(pa), len(pb)) {
		var x, y int
		if i < len(pa) {
			x, _ = strconv.Atoi(pa[i])
		}
		if i < len(pb) {
			y, _ = strconv.Atoi(pb[i])
		}
		if x != y {
			return x - y
		}
	}
	return 0
}

// atLeast raises a required_version constraint so it excludes Terraform
// releases older than minimum ("" leaves it as is).
func atLeast(constraint, minimum string) string {
	if minimum == "" {
		return constraint
	}
	if strings.TrimSpace(constraint) == "" {
		return ">= " + minimum
	}
	parts := strings.Split(constraint, ",")
	for _, part := range parts {
		part = strings.TrimSpace(part)
		op := strings.TrimRight(part, "0123456789. ")
		v := versionRe.FindString(part)
		switch strings.TrimSpace(op) {
		case ">=", "~>", "=", "", ">":
			if v != "" && compareVersions(v, minimum) >= 0 {
				return constraint
			}
		}
	}
	if len(parts) == 1 {
		part := strings.TrimSpace(parts[0])
		switch {
		case strings.HasPrefix(part, "~>"):
			return "~> " + minimum
		case strings.HasPrefix(part, ">="), strings.HasPrefix(part, ">"):
			return ">= " + minimum
		}
	}
	return constraint + ", >= " + minimum
}

// requiredVersion is the workflow's required_version constraint ("" without one).
func requiredVersion(wf *model.Workflow) string {
	if wf.Terraform == nil {
		return ""
	}
	s, _ := constStringExpr(getAttrValue(wf.Terraform, "required_version"))
	return s
}

// providerAliases lists the aliased provider configurations ("aws.east").
func providerAliases(wf *model.Workflow) map[string][]string {
	out := map[string][]string{}
	for i := range wf.Providers {
		p := &wf.Providers[i]
		if alias, ok := constStringExpr(getAttrValue(&p.Body, "alias")); ok && alias != "" {
			out[p.Name] = append(out[p.Name], p.Name+"."+alias)
		}
	}
	return out
}

// moduleVersions is the service module's terraform block: required_version
// and required_providers as minimums (>=), with configuration_aliases.
func (l *envLayout) moduleVersions() *model.Body {
	tf := &model.Body{Attrs: []model.Attr{}, Blocks: []model.Block{}}
	if v := minimumConstraint(l.rootRequiredVersion()); v != "" {
		tf.Attrs = append(tf.Attrs, model.Attr{Name: "required_version", Value: stringValue(v)})
	}
	aliases := providerAliases(l.wf)
	names := requiredProviderNames(l.wf)
	for local := range aliases {
		if !slices.Contains(names, local) {
			names = append(names, local)
		}
	}
	if len(names) == 0 {
		return tf
	}
	rp := model.Block{Type: "required_providers", Body: model.Body{Attrs: []model.Attr{}, Blocks: []model.Block{}}}
	seen := map[string]bool{}
	for _, local := range names {
		if seen[local] {
			continue
		}
		seen[local] = true
		source, version := requiredProvider(l.wf, local)
		if source == "" {
			source = strconv.Quote("hashicorp/" + local)
		}
		var sb strings.Builder
		sb.WriteString("{\nsource = " + source + "\n")
		if c, ok := constStringExpr(version); ok {
			if m := minimumConstraint(c); m != "" {
				sb.WriteString("version = " + strconv.Quote(m) + "\n")
			}
		}
		if as := aliases[local]; len(as) > 0 {
			sb.WriteString("configuration_aliases = [" + strings.Join(as, ", ") + "]\n")
		}
		sb.WriteString("}")
		rp.Body.Attrs = append(rp.Body.Attrs, model.Attr{Name: local, Value: model.Value{Expr: sb.String()}})
	}
	tf.Blocks = append(tf.Blocks, rp)
	return tf
}

// rootVersions is a root's terraform block without the state backend: the
// workflow's settings, required_version raised to what the backend needs.
func (l *envLayout) rootVersions() *model.Body {
	tf := &model.Body{Attrs: []model.Attr{}, Blocks: []model.Block{}}
	if l.wf.Terraform != nil {
		for _, a := range l.wf.Terraform.Attrs {
			a.File, a.Order, a.Comments = "", 0, nil
			tf.Attrs = append(tf.Attrs, a)
		}
		for _, b := range l.wf.Terraform.Blocks {
			if b.Type == "backend" || b.Type == "cloud" {
				continue
			}
			b = cloneBlock(b)
			b.File, b.Order = "", 0
			tf.Blocks = append(tf.Blocks, b)
		}
	}
	if v := l.rootRequiredVersion(); v != requiredVersion(l.wf) {
		setAttr(tf, "required_version", stringValue(v), true)
	}
	return tf
}

// rootRequiredVersion is the workflow's required_version raised to what the
// state backend needs (use_lockfile: 1.10; oci: 1.12).
func (l *envLayout) rootRequiredVersion() string {
	if l.backend == nil {
		return requiredVersion(l.wf)
	}
	return atLeast(requiredVersion(l.wf), l.backend.minTF)
}

// RequiredVersion is the Terraform version constraint the exported code
// needs ("" without one): the roots' required_version (the workflow's,
// raised in the environments layout to what the state backend needs) and,
// in the single layout, what backend.tf.example needs once copied to
// backend.tf.
func RequiredVersion(wf *model.Workflow) string {
	if layout, err := ResolveLayout(wf); err == nil && layout == model.LayoutEnvironments {
		if l, err := newEnvLayout(wf); err == nil {
			return l.rootRequiredVersion()
		}
	}
	if !HasBackend(wf) {
		if plan := defaultBackend(primaryCloud(wf), ServiceName(wf)); plan != nil {
			return atLeast(requiredVersion(wf), plan.minTF)
		}
	}
	return requiredVersion(wf)
}

// HasBackend reports a backend or cloud block of the workflow.
func HasBackend(wf *model.Workflow) bool {
	if wf.Terraform == nil {
		return false
	}
	for _, b := range wf.Terraform.Blocks {
		if b.Type == "backend" || b.Type == "cloud" {
			return true
		}
	}
	return false
}

