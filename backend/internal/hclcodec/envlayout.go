func (l *envLayout) makefile() []byte {
	names := make([]string, len(l.envs))
	for i, e := range l.envs {
		names[i] = e.Name
	}
	var b strings.Builder
	b.WriteString(makefileMarker + "\n")
	b.WriteString("# Terraform for one environment at a time, e.g. make plan ENV=" + names[len(names)-1] + "\n\n")
	b.WriteString("ENV ?= " + l.makefileDefault() + "\n")
	b.WriteString("ENVS := " + strings.Join(names, " ") + "\n")
	b.WriteString("TERRAFORM ?= terraform\n")
	b.WriteString("DIR := " + EnvironmentsDir + "/$(ENV)\n")
	b.WriteString("BACKEND_CONFIG := $(if $(wildcard $(DIR)/backend.hcl),-backend-config=backend.hcl)\n\n")
	b.WriteString("ifeq ($(filter $(ENV),$(ENVS)),)\n$(error unknown ENV \"$(ENV)\": use one of $(ENVS))\nendif\n\n")
	b.WriteString(".PHONY: init plan apply fmt validate\n\n")
	b.WriteString("init:\n\t$(TERRAFORM) -chdir=$(DIR) init $(BACKEND_CONFIG)\n\n")
	b.WriteString("plan:\n\t$(TERRAFORM) -chdir=$(DIR) plan -out=terraform.tfplan\n\n")
	b.WriteString("apply:\n\t$(TERRAFORM) -chdir=$(DIR) apply terraform.tfplan\n\n")
	b.WriteString("fmt:\n\t$(TERRAFORM) fmt -recursive\n\n")
	b.WriteString("validate:\n\t$(TERRAFORM) -chdir=$(DIR) init -backend=false -input=false\n\t$(TERRAFORM) -chdir=$(DIR) validate\n")
	return []byte(b.String())
}

func (l *envLayout) readme() []byte {
	var b strings.Builder
	line := func(s ...string) {
		for _, x := range s {
			b.WriteString(x)
			b.WriteByte('\n')
		}
	}
	title := strings.TrimSpace(l.wf.Name)
	if title == "" {
		title = "Terraform configuration"
	}
	line(readmeMarker, "", "# "+mdText(title), "")
	if d := strings.TrimSpace(l.wf.Description); d != "" {
		line(d, "")
	}
	var mods []string
	for i := range l.wf.Nodes {
		if dir, ok := LocalModuleDir(&l.wf.Nodes[i]); ok && path.Dir(dir) == ModulesDir && !slices.Contains(mods, path.Base(dir)) {
			mods = append(mods, path.Base(dir))
		}
	}
	slices.Sort(mods)
	line("## Layout", "", "```text", ".", "├── Makefile", "├── modules/")
	line(fmt.Sprintf("│   %s %s/ # the service: every resource, no provider configuration", treeBranch(len(mods) == 0), l.svc))
	for i, m := range mods {
		line(fmt.Sprintf("│   %s %s/ # local module called by %s", treeBranch(i == len(mods)-1), m, l.svc))
	}
	line("└── " + EnvironmentsDir + "/")
	for i, e := range l.envs {
		line(fmt.Sprintf("    %s %s/ # root module: backend, providers, values; its own state", treeBranch(i == len(l.envs)-1), e.Name))
	}
	line("```", "")
	line("Each environment is its own root module with its own state: `"+EnvironmentsDir+"/<env>/main.tf` calls `modules/"+l.svc+
		"` with that environment's values (`terraform.tfvars`), and `backend.tf` keeps its state apart, so a plan of one environment never touches another.", "")

	first := l.makefileDefault()
	line("## Usage", "", "```sh")
	if l.backend != nil && len(l.backend.example) > 0 {
		line(fmt.Sprintf("cp %s/%s/%s %s/%s/backend.hcl   # then set your state storage", EnvironmentsDir, first, BackendExampleFile, EnvironmentsDir, first))
		line(fmt.Sprintf("terraform -chdir=%s/%s init -backend-config=backend.hcl", EnvironmentsDir, first))
	} else {
		line(fmt.Sprintf("terraform -chdir=%s/%s init", EnvironmentsDir, first))
	}
	line(fmt.Sprintf("terraform -chdir=%s/%s plan -out=terraform.tfplan", EnvironmentsDir, first))
	line(fmt.Sprintf("terraform -chdir=%s/%s apply terraform.tfplan", EnvironmentsDir, first))
	line("```", "")
	line("The Makefile runs the same commands for `ENV` (default `"+l.makefileDefault()+"`):", "")
	line("| Target | Runs |", "|--------|------|")
	line("| `make init ENV=<env>` | `terraform init` (with `backend.hcl` when present) |")
	line("| `make plan ENV=<env>` | `terraform plan -out=terraform.tfplan` |")
	line("| `make apply ENV=<env>` | `terraform apply terraform.tfplan` |")
	line("| `make validate ENV=<env>` | `terraform init -backend=false` + `terraform validate` |")
	line("| `make fmt` | `terraform fmt -recursive` |", "")

	line("## Environments", "", "| Environment | Root | State |", "|-------------|------|-------|")
	for _, e := range l.envs {
		state := "local (`terraform.tfstate` in the root)"
		if l.backend != nil {
			state = "`" + l.backend.kind + "`"
			if l.backend.key != nil {
				state += " " + l.backend.key.attr + " `" + l.backend.key.perEnv(l.backend.base, e.Name) + "`"
			}
		}
		line("| " + mdText(e.Name) + " | `" + EnvironmentsDir + "/" + e.Name + "` | " + state + " |")
	}
	line("")
	var required, secrets []string
	for _, v := range l.sortedVars() {
		if v.used && !v.moduleDefault() || v.used && v.def == "" {
			required = append(required, "`"+v.block.Name+"`")
		}
		if v.secret && v.passed {
			secrets = append(secrets, "`TF_VAR_"+v.block.Name+"`")
		}
	}
	if len(required) > 0 {
		line("Inputs the service module takes without a default (every root passes them: their values differ between environments, or the root reads them too and holds the default): "+strings.Join(required, ", ")+".", "")
	}
	line("Secrets are never written to a variable file: export them as `TF_VAR_<name>` environment variables (each environment's `.env.example` lists the ones it needs).")
	if len(secrets) > 0 {
		line("This configuration needs " + strings.Join(secrets, ", ") + ".")
	}
	line("", "## Service module", "", "See [`modules/"+l.svc+"/README.md`](modules/"+l.svc+"/README.md) for its inputs and outputs.")
	return []byte(b.String())
}

func (l *envLayout) makefileDefault() string {
	for _, e := range l.envs {
		if e.Name == "dev" {
			return "dev"
		}
	}
	return l.envs[0].Name
}

func treeBranch(last bool) string {
	if last {
		return "└──"
	}
	return "├──"
}

