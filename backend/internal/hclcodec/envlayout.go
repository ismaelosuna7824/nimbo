// State backend

// stateKey is the backend setting that has to differ per environment.
type stateKey struct {
	block string // nested block holding attr ("" = the backend body)
	attr  string
	shape int
}

const (
	// shapeDir: "<dir>/<env>/<file>" (a state object key).
	shapeDir = iota
	// shapeAppend: "<prefix>/<env>" (a state object prefix).
	shapeAppend
	// shapeSuffix: "<name>-<env>" (an HCP Terraform workspace).
	shapeSuffix
)

// stateKeys by backend type ("cloud" for the HCP Terraform block). Other
// backend types are written to every root unchanged.
var stateKeys = map[string]stateKey{
	"s3":      {attr: "key", shape: shapeDir},
	"azurerm": {attr: "key", shape: shapeDir},
	"oci":     {attr: "key", shape: shapeDir},
	"gcs":     {attr: "prefix", shape: shapeAppend},
	"cloud":   {block: "workspaces", attr: "name", shape: shapeSuffix},
}

// perEnv derives the environment's value from the workflow's.
func (k stateKey) perEnv(base, env string) string {
	switch k.shape {
	case shapeAppend:
		if base = strings.Trim(base, "/"); base == "" {
			return env
		}
		return base + "/" + env
	case shapeSuffix:
		return base + "-" + env
	}
	dir, file := path.Split(base)
	return dir + env + "/" + file
}

// general is the inverse of perEnv.
func (k stateKey) general(v, env string) (string, bool) {
	switch k.shape {
	case shapeAppend:
		if v == env {
			return "", true
		}
		return strings.CutSuffix(v, "/"+env)
	case shapeSuffix:
		return strings.CutSuffix(v, "-"+env)
	}
	dir, file := path.Split(v)
	if file == "" {
		return "", false
	}
	if dir == env+"/" {
		return file, true
	}
	if d, ok := strings.CutSuffix(dir, "/"+env+"/"); ok {
		return d + "/" + file, true
	}
	return "", false
}

// backendPlan is the state configuration of every root.
type backendPlan struct {
	block model.Block // a "backend" block (or the "cloud" block) of the workflow or the cloud default
	kind  string      // backend type, or "cloud"
	key   *stateKey   // nil: the same in every root
	base  string      // the workflow's value of the key
	// example: the cloud default, completed by backend.hcl (example lines).
	example []string
	minTF   string // oldest Terraform that reads the configuration
}

// defaultBackend is the remote state of a cloud: a partial configuration
// whose storage location comes from backend.hcl.
func defaultBackend(cloud model.Cloud, svc string) *backendPlan {
	tru := model.Value{Expr: "true"}
	b := &backendPlan{block: model.Block{Type: "backend", Body: model.Body{Attrs: []model.Attr{}, Blocks: []model.Block{}}}}
	attr := func(name string, v model.Value) {
		b.block.Body.Attrs = append(b.block.Body.Attrs, model.Attr{Name: name, Value: v})
	}
	bucket := strings.ReplaceAll(svc, "_", "-") + "-terraform-state"
	switch cloud {
	case model.CloudAWS:
		b.kind, b.minTF = "s3", "1.10"
		b.base = svc + "/terraform.tfstate"
		attr("key", stringValue(""))
		attr("encrypt", tru)
		attr("use_lockfile", tru) // S3 native locking (DynamoDB locking is deprecated)
		b.example = []string{`bucket = "` + bucket + `"`, `region = "us-east-1"`}
	case model.CloudAzure:
		b.kind = "azurerm"
		b.base = svc + "/terraform.tfstate"
		attr("key", stringValue(""))
		attr("use_azuread_auth", tru)
		account := strings.NewReplacer("_", "", "-", "").Replace(svc)
		if len(account) > 17 {
			account = account[:17]
		}
		b.example = []string{`resource_group_name  = "terraform-state"`, `storage_account_name = "` + account + `tfstate"`, `container_name       = "tfstate"`}
	case model.CloudGCP:
		b.kind = "gcs"
		b.base = svc
		attr("prefix", stringValue(""))
		b.example = []string{`bucket = "` + bucket + `"`}
	case model.CloudOCI:
		b.kind, b.minTF = "oci", "1.12"
		b.base = svc + "/terraform.tfstate"
		attr("key", stringValue(""))
		b.example = []string{`bucket    = "` + bucket + `"`, `namespace = "<object storage namespace>"`, `region    = "us-ashburn-1"`}
	default:
		return nil
	}
	b.block.Labels = []string{b.kind}
	k := stateKeys[b.kind]
	b.key = &k
	return b
}

// newBackendPlan is the workflow's own backend (or cloud) block with its
// state key per environment, else the default of its cloud (nil without a
// cloud: each root keeps a local state in its own directory).
func newBackendPlan(wf *model.Workflow, cloud model.Cloud, svc string) *backendPlan {
	var own *model.Block
	if wf.Terraform != nil {
		for i := range wf.Terraform.Blocks {
			if t := wf.Terraform.Blocks[i].Type; t == "backend" || t == "cloud" {
				own = &wf.Terraform.Blocks[i]
				break
			}
		}
	}
	if own == nil {
		return defaultBackend(cloud, svc)
	}
	b := &backendPlan{block: *own, kind: own.Type}
	if own.Type == "backend" && len(own.Labels) == 1 {
		b.kind = own.Labels[0]
	}
	if k, ok := stateKeys[b.kind]; ok {
		holder := &b.block.Body
		if k.block != "" {
			holder = nil
			for i := range b.block.Body.Blocks {
				if b.block.Body.Blocks[i].Type == k.block {
					holder = &b.block.Body.Blocks[i].Body
				}
			}
		}
		if holder != nil {
			b.key = &k
			if s, ok := constStringExpr(getAttrValue(holder, k.attr)); ok {
				b.base = s
			} else {
				b.base = defaultBase(k, svc)
			}
		}
	}
	if b.kind == "s3" && getAttrValue(&b.block.Body, "use_lockfile") == "true" {
		b.minTF = "1.10"
	}
	if b.kind == "oci" {
		b.minTF = "1.12"
	}
	return b
}

// forEnv is the backend block of one root.
func (b *backendPlan) forEnv(env string) model.Block {
	blk := cloneBlock(b.block)
	if b.key == nil {
		return blk
	}
	holder := &blk.Body
	if b.key.block != "" {
		holder = nil
		for i := range blk.Body.Blocks {
			if blk.Body.Blocks[i].Type == b.key.block {
				holder = &blk.Body.Blocks[i].Body
			}
		}
		if holder == nil {
			return blk
		}
	}
	setAttr(holder, b.key.attr, stringValue(b.key.perEnv(b.base, env)), true)
	return blk
}

// defaultBase is the workflow-level state key of the service svc.
func defaultBase(k stateKey, svc string) string {
	if k.shape == shapeDir {
		return svc + "/terraform.tfstate"
	}
	return svc
}

// setAttr replaces an attribute's value in place, or adds it (first when
// front is set).
func setAttr(b *model.Body, name string, v model.Value, front bool) {
	for i := range b.Attrs {
		if b.Attrs[i].Name == name {
			b.Attrs[i].Value = v
			return
		}
	}
	a := model.Attr{Name: name, Value: v}
	if front {
		b.Attrs = append([]model.Attr{a}, b.Attrs...)
	} else {
		b.Attrs = append(b.Attrs, a)
	}
}

func removeAttr(b *model.Body, name string) {
	b.Attrs = slices.DeleteFunc(b.Attrs, func(a model.Attr) bool { return a.Name == name })
}

func cloneBlock(b model.Block) model.Block {
	b.Labels = slices.Clone(b.Labels)
	b.Body = cloneBody(b.Body)
	return b
}

func cloneBody(b model.Body) model.Body {
	out := model.Body{Attrs: slices.Clone(b.Attrs), Blocks: make([]model.Block, len(b.Blocks)), Comments: b.Comments}
	if out.Attrs == nil {
		out.Attrs = []model.Attr{}
	}
	for i := range b.Blocks {
		out.Blocks[i] = cloneBlock(b.Blocks[i])
	}
	return out
}

