// kubeMonitoringSources finds the kube-prometheus-stack helm source (the
// chart or a wrapper depending on it) and the generated manifests source
// (-1 when absent).
func kubeMonitoringSources(wf *model.Workflow) (chart, manifests int) {
	chart, manifests = -1, -1
	for i, src := range wf.Kubernetes.Sources {
		switch {
		case src.Kind == model.KubeHelm && chart < 0 && isPromStack(src.Chart):
			chart = i
		case src.Kind == model.KubeManifests && path.Clean(src.Path) == monitoring.KubeDir:
			manifests = i
		}
	}
	return chart, manifests
}

func isPromStack(c *model.KubeChart) bool {
	if c == nil {
		return false
	}
	if c.Name == monitoring.KubeChartName {
		return true
	}
	for _, d := range c.Dependencies {
		if d.Name == monitoring.KubeChartName {
			return true
		}
	}
	return false
}

// planKubeMonitoring generates the manifests source from the workflow's
// workloads in every environment (the monitoring's own sources left out).
func (s *Server) planKubeMonitoring(wf *model.Workflow, p *kube.Project, override *model.MonitoringThresholds) (out monitoring.KubeOutput, chart, man int, ns string, err error) {
	chart, man = kubeMonitoringSources(wf)
	ns = monitoring.KubeNamespace
	if chart >= 0 {
		src := wf.Kubernetes.Sources[chart]
		ns = cmpOr(src.Namespace, src.Release, "default")
	}
	if man >= 0 {
		for _, f := range []string{"rules.yaml", "dashboards.yaml"} {
			data, rerr := p.Read(monitoring.KubeDir + "/" + f)
			if rerr == nil && !monitoring.IsGenerated(data) {
				return out, chart, man, ns, errorf(http.StatusConflict, "%s/%s was not generated by Add monitoring: move the monitoring/ source elsewhere, then add monitoring again", monitoring.KubeDir, f)
			}
		}
	}
	// The workflow without the monitoring, rendered per environment.
	app := *wf
	k := *wf.Kubernetes
	k.Sources = nil
	for i, src := range wf.Kubernetes.Sources {
		if i != chart && i != man {
			k.Sources = append(k.Sources, src)
		}
	}
	app.Kubernetes = &k
	var envs []string
	for _, e := range wf.Environments {
		envs = append(envs, e.Name)
	}
	if len(envs) == 0 {
		envs = []string{p.Environment}
	}
	var projects []*kube.Project
	for _, env := range envs {
		projects = append(projects, kube.Open(context.Background(), s.cfg.Store.AssetsDir(wf.ID), &app, kube.Options{Environment: env, NoSourceMap: true}))
	}
	saved, _ := p.Read(monitoring.KubeRulesFile)
	t, err := monitoringThresholds(saved, override)
	if err != nil {
		return out, chart, man, ns, err
	}
	out = monitoring.Kube(monitoring.KubeInput{Projects: projects, Namespace: ns, Thresholds: t})
	return out, chart, man, ns, nil
}

func cmpOr(vals ...string) string {
	for _, v := range vals {
		if v != "" {
			return v
		}
	}
	return ""
}

// kubeMonitoringFiles lists the files Add monitoring writes.
func kubeMonitoringFiles(out monitoring.KubeOutput, withChart bool) []string {
	var files []string
	for f, data := range out.Files {
		if data != nil {
			files = append(files, f)
		}
	}
	if withChart {
		dir := "charts/" + monitoring.KubeChartName
		files = append(files, dir+"/Chart.yaml", dir+"/values.yaml", monitoring.KubeAdminSecretFile(dir), dir+"/charts/"+monitoring.KubeChartName+"-"+monitoring.KubeChart().Version+".tgz")
	}
	slices.Sort(files)
	return files
}

func (s *Server) addKubeMonitoring(ctx context.Context, cur *model.Workflow, override *model.MonitoringThresholds) (*model.MonitoringResult, error) {
	var cs *kubecatalog.ChartSource
	if chart, _ := kubeMonitoringSources(cur); chart < 0 {
		var err error
		// Download outside the edit lock (the chart is vendored: up works offline).
		if cs, err = kubecatalog.AddChart(ctx, http.DefaultClient, monitoring.KubeChartID, monitoring.KubeChartName, monitoring.KubeNamespace); err != nil {
			return nil, errorf(http.StatusBadGateway, "%s", err)
		}
	}
	var (
		out     monitoring.KubeOutput
		ns      string
		enabled bool
		added   bool
	)
	wf, err := s.editKube(cur.ID, func(wf *model.Workflow, p *kube.Project, _ *kube.Editor, files map[string][]byte) error {
		var (
			chart, man int
			err        error
		)
		if out, chart, man, ns, err = s.planKubeMonitoring(wf, p, override); err != nil {
			return err
		}
		enabled = chart >= 0 && man >= 0
		sources := wf.Kubernetes.Sources
		var chartSrc model.KubeSource
		if chart < 0 {
			if cs == nil {
				return errorf(http.StatusConflict, "the workflow changed while the chart downloaded: add monitoring again")
			}
			for _, src := range sources {
				if path.Clean(src.Path) == cs.Source.Path {
					return errorf(http.StatusConflict, "a source already uses %s: move it, then add monitoring again", cs.Source.Path)
				}
			}
			for f, data := range cs.Files {
				files[f] = data
			}
			files[cs.Source.Path+"/values.yaml"] = []byte(monitoring.KubeValues())
			files[monitoring.KubeAdminSecretFile(cs.Source.Path)] = monitoring.KubeAdminSecretYAML(monitoring.NewPassword())
			chartSrc, added = cs.Source, true
		} else {
			chartSrc = sources[chart]
		}
		for f, data := range out.Files {
			files[f] = data
		}
		manSrc := model.KubeSource{Kind: model.KubeManifests, Path: monitoring.KubeDir, Namespace: ns}
		if man >= 0 {
			manSrc = sources[man]
		}
		// The chart goes before the first other source with monitoring
		// custom resources (its CRDs must exist when they apply), else
		// last; the generated manifests right after it.
		hasCRs := map[int]bool{}
		for _, o := range p.Objects {
			if strings.HasPrefix(o.APIVersion, "monitoring.coreos.com/") {
				hasCRs[o.Source] = true
			}
		}
		var rest []model.KubeSource
		at := -1
		for i, src := range sources {
			if i == chart || i == man {
				continue
			}
			if at < 0 && hasCRs[i] {
				at = len(rest)
			}
			rest = append(rest, src)
		}
		if at < 0 {
			at = len(rest)
		}
		wf.Kubernetes.Sources = slices.Concat(rest[:at], []model.KubeSource{chartSrc, manSrc}, rest[at:])
		return nil
	})
	if err != nil {
		return nil, err
	}
	chart, _ := kubeMonitoringSources(wf)
	sum := monitoring.KubeSummary(out, kubeMonitoringFiles(out, added), true)
	sum.Credentials = s.kubeGrafanaCredentials(wf, chart)
	sum.Links = s.kubeMonitoringLinks(ctx, wf.ID, ns)
	if enabled {
		sum.Notes = append(sum.Notes, "Monitoring was already there: the alerts, scrape targets and dashboard were regenerated (chart values kept). Deploy again to apply them.")
	} else {
		sum.Notes = append(sum.Notes, "Deploy to install the stack (the first install pulls its images, a few minutes); Grafana and Prometheus then show in Endpoints.")
	}
	return &model.MonitoringResult{Workflow: wf, Summary: sum}, nil
}

// kubeGrafanaCredentials reads the Grafana admin password of the helm
// source (the Secret template Add monitoring wrote).
func (s *Server) kubeGrafanaCredentials(wf *model.Workflow, chart int) *model.MonitoringCredentials {
	if chart < 0 {
		return &model.MonitoringCredentials{User: "admin", Source: "a generated Secret (" + monitoring.KubeNamespace + "/" + monitoring.KubeAdminSecret + ")"}
	}
	src := wf.Kubernetes.Sources[chart]
	file := monitoring.KubeAdminSecretFile(path.Clean(src.Path))
	data, err := os.ReadFile(filepath.Join(s.cfg.Store.AssetsDir(wf.ID), filepath.FromSlash(file)))
	if err != nil {
		return &model.MonitoringCredentials{User: "admin", Source: "the chart's values (" + path.Join(src.Path, "values.yaml") + ")"}
	}
	return &model.MonitoringCredentials{User: "admin", Password: monitoring.KubeAdminPassword(data),
		Source: "Secret " + cmpOr(src.Namespace, src.Release) + "/" + monitoring.KubeAdminSecret + " (" + file + ")"}
}

// kubeMonitoringLinks are the forwards of Grafana, Prometheus and
// Alertmanager when the cluster runs (empty links before the deploy).
func (s *Server) kubeMonitoringLinks(ctx context.Context, wfID, ns string) []model.MonitoringLink {
	links := []model.MonitoringLink{{Name: "Grafana"}, {Name: "Prometheus"}, {Name: "Alertmanager"}}
	ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	st, err := s.cfg.Sandbox.KubeStatus(ctx, wfID)
	if err != nil {
		return links
	}
	match := map[string]func(model.KubeForward) bool{
		"Grafana":      func(f model.KubeForward) bool { return strings.HasSuffix(f.Service, "-grafana") },
		"Prometheus":   func(f model.KubeForward) bool { return strings.HasSuffix(f.Service, "-prometheus") && f.Port == 9090 },
		"Alertmanager": func(f model.KubeForward) bool { return strings.HasSuffix(f.Service, "-alertmanager") && f.Port == 9093 },
	}
	for i, l := range links {
		for _, f := range st.Forwards {
			if f.Namespace == ns && f.URL != "" && match[l.Name](f) {
				links[i].URL, links[i].Running = strings.TrimSuffix(f.URL, "/"), f.Ready
			}
		}
	}
	return links
}
