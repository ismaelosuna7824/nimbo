// Monitoring (package monitoring): GET /workflows/{id}/monitoring previews
// what Add monitoring adds (or added) and the local URLs; POST adds it, or
// regenerates it when it is there (never duplicating services or sources).
// Docker workflows get a monitoring/compose.yaml listed after their compose
// files; Kubernetes workflows the kube-prometheus-stack helm source and a
// monitoring/ manifests source right after it.

// getMonitoring is GET /workflows/{id}/monitoring.
func (s *Server) getMonitoring(w http.ResponseWriter, r *http.Request) error {
	wf, err := s.cfg.Store.Get(r.PathValue("id"))
	if err != nil {
		return err
	}
	var sum model.MonitoringSummary
	switch {
	case wf.IsDocker():
		p := s.openCompose(wf, nil)
		out, err := s.planDockerMonitoring(wf, p, nil)
		if err != nil {
			return err
		}
		sum = out.Summary
		sum.Enabled = slices.Contains(wf.Compose.Files, out.File)
		if !sum.Enabled {
			sum.Credentials.Password = "" // generated when added
		} else if st, err := s.cfg.Sandbox.ComposeStatus(r.Context(), wf.ID, composeServices(wf)); err == nil {
			dockerMonitoringLinks(&sum, st)
		}
	case wf.IsKubernetes():
		out, chart, man, ns, err := s.planKubeMonitoring(wf, s.openKube(wf, nil), nil)
		if err != nil {
			return err
		}
		sum = monitoring.KubeSummary(out, kubeMonitoringFiles(out, chart < 0), chart >= 0 && man >= 0)
		sum.Credentials = s.kubeGrafanaCredentials(wf, chart)
		sum.Links = s.kubeMonitoringLinks(r.Context(), wf.ID, ns)
	default:
		return errorf(http.StatusBadRequest, "monitoring is for docker and Kubernetes workflows; %s is a %s workflow", wf.Name, model.KindLabel(wf.Kind))
	}
	return ok(w, sum)
}

// addMonitoring is POST /workflows/{id}/monitoring (optional body
// model.MonitoringRequest): it answers {workflow, summary}.
func (s *Server) addMonitoring(w http.ResponseWriter, r *http.Request) error {
	var req model.MonitoringRequest
	if r.ContentLength != 0 {
		if err := decode(w, r, maxBody, &req); err != nil {
			return err
		}
	}
	id := r.PathValue("id")
	cur, err := s.cfg.Store.Get(id)
	if err != nil {
		return err
	}
	var res *model.MonitoringResult
	switch {
	case cur.IsDocker():
		res, err = s.addDockerMonitoring(r.Context(), id, req.Thresholds)
	case cur.IsKubernetes():
		res, err = s.addKubeMonitoring(r.Context(), cur, req.Thresholds)
	default:
		return errorf(http.StatusBadRequest, "monitoring is for docker and Kubernetes workflows; %s is a %s workflow", cur.Name, model.KindLabel(cur.Kind))
	}
	if err != nil {
		return err
	}
	return ok(w, res)
}

