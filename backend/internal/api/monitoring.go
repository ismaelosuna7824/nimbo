// monitoringThresholds are the HTTP alert thresholds: the generated rules
// file's (saved, nil when absent), overridden by the request's non-zero
// fields, defaults for the rest.
func monitoringThresholds(saved []byte, override *model.MonitoringThresholds) (model.MonitoringThresholds, error) {
	t := monitoring.ParseThresholds(saved)
	if o := override; o != nil {
		if o.ErrorPercent != 0 {
			t.ErrorPercent = o.ErrorPercent
		}
		if o.LatencyP95Ms != 0 {
			t.LatencyP95Ms = o.LatencyP95Ms
		}
		if o.MinRequestsPerSecond != 0 {
			t.MinRequestsPerSecond = o.MinRequestsPerSecond
		}
	}
	t, err := monitoring.ValidThresholds(t)
	if err != nil {
		return t, errorf(http.StatusBadRequest, "thresholds: %s", err)
	}
	return t, nil
}

// planDockerMonitoring generates the docker stack for wf's project p.
func (s *Server) planDockerMonitoring(wf *model.Workflow, p *compose.Project, override *model.MonitoringThresholds) (*monitoring.ComposeOutput, error) {
	file := monitoring.ComposeFile(p.ProjectDir)
	if data, err := os.ReadFile(filepath.Join(s.cfg.Store.AssetsDir(wf.ID), filepath.FromSlash(file))); err == nil && !monitoring.IsGenerated(data) {
		return nil, errorf(http.StatusConflict, "%s exists and was not generated by Add monitoring: move it, then add monitoring again", file)
	}
	saved, _ := os.ReadFile(filepath.Join(s.cfg.Store.AssetsDir(wf.ID), filepath.FromSlash(monitoring.ComposeAlertsFile(p.ProjectDir))))
	t, err := monitoringThresholds(saved, override)
	if err != nil {
		return nil, err
	}
	out, err := monitoring.Compose(monitoring.ComposeInput{Project: p, ProjectName: model.ComposeProjectName(wf.ID), Password: p.Env[monitoring.GrafanaPasswordVar], Thresholds: t})
	var conflict *monitoring.ConflictError
	switch {
	case errors.As(err, &conflict):
		return nil, errorf(http.StatusConflict, "%s", err)
	case err != nil:
		return nil, errorf(http.StatusBadRequest, "%s", err)
	}
	return out, nil
}

func (s *Server) addDockerMonitoring(ctx context.Context, id string, override *model.MonitoringThresholds) (*model.MonitoringResult, error) {
	var out *monitoring.ComposeOutput
	enabled := false
	wf, err := s.editCompose(id, func(wf *model.Workflow, p *compose.Project, _ *compose.Editor, extra map[string][]byte) error {
		var err error
		if out, err = s.planDockerMonitoring(wf, p, override); err != nil {
			return err
		}
		for f, data := range out.Files {
			extra[f] = data
		}
		if out.NewPassword {
			envFile := path.Join(p.ProjectDir, ".env")
			cur, err := os.ReadFile(filepath.Join(s.cfg.Store.AssetsDir(wf.ID), filepath.FromSlash(envFile)))
			if err != nil && !errors.Is(err, fs.ErrNotExist) {
				return err
			}
			if len(cur) > 0 && cur[len(cur)-1] != '\n' {
				cur = append(cur, '\n')
			}
			extra[envFile] = append(cur, fmt.Sprintf("# Grafana admin password (Add monitoring; keep real credentials out of git)\n%s=%s\n", monitoring.GrafanaPasswordVar, out.Password)...)
		}
		enabled = slices.Contains(wf.Compose.Files, out.File)
		if !enabled {
			wf.Compose.Files = append(wf.Compose.Files, out.File)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sum := out.Summary
	sum.Enabled = true
	if st, err := s.cfg.Sandbox.ComposeStatus(ctx, wf.ID, composeServices(wf)); err == nil {
		dockerMonitoringLinks(&sum, st)
	}
	if enabled {
		sum.Notes = append(sum.Notes, "Monitoring was already there: its files were regenerated. Deploy again to apply them.")
	} else {
		sum.Notes = append(sum.Notes, "Deploy to start Prometheus, Grafana and cAdvisor.")
	}
	return &model.MonitoringResult{Workflow: wf, Summary: sum}, nil
}

// dockerMonitoringLinks points the links at the running containers' host
// ports (a busy port may have been remapped at up).
func dockerMonitoringLinks(sum *model.MonitoringSummary, st model.ComposeStatus) {
	ports := map[string]int{"Grafana": 3000, "Prometheus": 9090}
	svcs := map[string]string{"Grafana": monitoring.GrafanaService, "Prometheus": monitoring.PrometheusService}
	for i, l := range sum.Links {
		for _, svc := range st.Services {
			if svc.Name != svcs[l.Name] {
				continue
			}
			for _, c := range svc.Containers {
				for _, p := range c.Ports {
					if p.Container == ports[l.Name] && p.URL != "" && c.State == "running" {
						sum.Links[i].URL, sum.Links[i].Running = strings.TrimSuffix(p.URL, "/"), true
					}
				}
			}
		}
	}
}

