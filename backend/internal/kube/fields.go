// Field origins (model.KubeField.Via).
const (
	ViaManifest      = "manifest"
	ViaPatch         = "patch"
	ViaKustomization = "kustomization"
	ViaValues        = "values"
	ViaTemplate      = "template"
)

// fieldSource is where one field comes from, with what a write needs.
type fieldSource struct {
	model.KubeField
	// docKeys are the keys/indexes of the field in the document File
	// holds (manifest/patch), or of the values key (values, one key).
	docKeys []string
	doc     int // document index in File (manifest/patch)
	// kustomization transformer entries: images[i] or replicas[i].
	transformer string
	item        int
	// values pattern (several keys, or literals around one key).
	pattern *valuesPattern
	// valuesFiles: the file holding each of pattern's keys.
	valuesFiles []string
	// helm and cur: the source's render and the keys' current values.
	helm *helmRender
	cur  []string
	// template literal: the token to replace on Line.
	literal string
}

// Fields returns where every scalar field of o comes from.
func (p *Project) Fields(o *Object) []model.KubeField {
	srcs := p.fieldSources(o, nil)
	out := make([]model.KubeField, 0, len(srcs))
	for _, s := range srcs {
		out = append(out, s.KubeField)
	}
	return out
}

// fieldSources maps the fields of o (only only, when set: those paths).
func (p *Project) fieldSources(o *Object, only [][]seg) []*fieldSource {
	r := p.Source(o)
	var ls []leaf
	if only == nil {
		ls = leaves(o.Obj)
	} else {
		for _, segs := range only {
			keys, _, _ := concrete(o.Obj, segs)
			v, _ := at(o.Obj, keys)
			ls = append(ls, leaf{segs: segs, keys: keys, value: v})
		}
	}
	var hm *helmMap
	if r != nil && r.Source.Kind == model.KubeHelm {
		hm = p.helmSourceMap(r)
	}
	out := make([]*fieldSource, 0, len(ls))
	var srcFile *File
	if o.Doc >= 0 && o.File != "" {
		if data, err := p.fs.read(o.File); err == nil {
			srcFile = ParseFile(o.File, data)
		}
	}
	for _, l := range ls {
		fs := &fieldSource{KubeField: model.KubeField{Path: FormatPath(l.segs), Value: l.value}}
		switch {
		case r == nil:
			fs.Reason = "the object's source is unknown"
		case r.Source.Kind == model.KubeHelm:
			p.helmField(o, r, hm, l, fs)
		case o.generated:
			fs.File, fs.Line = o.File, o.Line
			fs.Reason = "generated by a configMapGenerator/secretGenerator: edit its entry in " + o.File
		case r.Source.Kind == model.KubeKustomize:
			p.kustField(o, r, srcFile, l, fs)
		default:
			manifestField(o, srcFile, l, fs)
		}
		out = append(out, fs)
	}
	return out
}

// docField locates segs in document doc of f.
func docField(f *File, doc int, segs []seg) (keys []string, line int, ok bool) {
	if f == nil {
		return nil, 0, false
	}
	docs := f.Docs()
	if doc < 0 || doc >= len(docs) {
		return nil, 0, false
	}
	s := docs[doc]
	var m map[string]any
	if s.Doc.Root.Decode(&m) != nil {
		return nil, 0, false
	}
	keys, missing, found := concrete(normalize(m), segs)
	if !found || missing {
		return keys, 0, false
	}
	line = s.Doc.LocatePath(keys)
	return keys, s.Line(line), true
}

func manifestField(o *Object, f *File, l leaf, fs *fieldSource) {
	keys, line, ok := docField(f, o.Doc, l.segs)
	fs.File, fs.Line = o.File, o.Line
	if !ok {
		fs.Reason = "not found in " + o.File
		return
	}
	fs.Editable, fs.Via, fs.Line, fs.docKeys, fs.doc = true, ViaManifest, line, keys, o.Doc
	if strings.HasSuffix(o.File, ".json") {
		fs.Editable, fs.Reason = false, "a JSON manifest: edit it in the Code tab"
	}
}

// ---------------------------------------------------------------------------
// Kustomize

func (p *Project) kustField(o *Object, r *Rendered, f *File, l leaf, fs *fieldSource) {
	fs.File, fs.Line = o.File, o.Line
	tree := r.kust
	if tree == nil {
		fs.Reason = "the kustomization can't be read"
		return
	}
	// Transformers in kustomizations, nearest (overlay) first.
	last := l.segs[len(l.segs)-1]
	if last.Key == "image" && inContainers(l.segs) {
		srcImage := ""
		if keys, _, ok := docField(f, o.Doc, l.segs); ok {
			if v, ok := at(docValue(f, o.Doc), keys); ok {
				srcImage = fmt.Sprint(v)
			}
		}
		for _, n := range tree.Nodes {
			for i, it := range list(n.Data["images"]) {
				name := str(it, "name")
				if name != "" && (imageRepo(srcImage) == name || imageRepo(fmt.Sprint(l.value)) == name || imageRepo(srcImage) == imageRepo(str(it, "newName"))) {
					fs.Editable, fs.Via = true, ViaKustomization
					fs.File, fs.Line = n.File, n.Doc.LocatePath([]string{"images", itoa(i)})
					fs.transformer, fs.item = "images", i
					return
				}
			}
		}
	}
	if FormatPath(l.segs) == "spec.replicas" {
		for _, n := range tree.Nodes {
			for i, it := range list(n.Data["replicas"]) {
				if str(it, "name") == o.orgName || str(it, "name") == o.Name {
					fs.Editable, fs.Via = true, ViaKustomization
					fs.File, fs.Line = n.File, n.Doc.LocatePath([]string{"replicas", itoa(i), "count"})
					fs.transformer, fs.item = "replicas", i
					return
				}
			}
		}
	}
	// Patches, nearest first.
	for _, n := range tree.Nodes {
		if p.kustPatchField(o, n, l, fs) {
			return
		}
	}
	keys, line, ok := docField(f, o.Doc, l.segs)
	if !ok {
		fs.File, fs.Line = tree.Nodes[0].File, 1
		fs.Reason = "added by a kustomization transformer (labels, annotations, namespace, name prefix...): edit " + tree.Nodes[0].File
		return
	}
	if v, ok := at(docValue(f, o.Doc), keys); ok && fmt.Sprint(v) != fmt.Sprint(l.value) && isScalar(l.value) {
		fs.Line = line
		fs.Reason = fmt.Sprintf("%s holds %v, the kustomization changes it (name prefix/suffix, namespace, labels or a replacement)", o.File, v)
		return
	}
	fs.Editable, fs.Via, fs.Line, fs.docKeys, fs.doc = true, ViaManifest, line, keys, o.Doc
	if strings.HasSuffix(o.File, ".json") {
		fs.Editable, fs.Reason = false, "a JSON manifest: edit it in the Code tab"
	}
}

func isScalar(v any) bool {
	switch v.(type) {
	case map[string]any, []any:
		return false
	}
	return true
}

func inContainers(segs []seg) bool {
	for _, s := range segs {
		if s.Key == "containers" || s.Key == "initContainers" {
			return true
		}
	}
	return false
}

func imageRepo(img string) string {
	if ref := compose.ParseImage(img); ref != nil {
		return ref.Repo
	}
	return ""
}

func docValue(f *File, doc int) any {
	if f == nil {
		return nil
	}
	docs := f.Docs()
	if doc < 0 || doc >= len(docs) {
		return nil
	}
	var m map[string]any
	if docs[doc].Doc.Root.Decode(&m) != nil {
		return nil
	}
	return normalize(m)
}

// kustPatchField finds the field in a patch of kustomization n targeting o.
func (p *Project) kustPatchField(o *Object, n *kustNode, l leaf, fs *fieldSource) bool {
	targets := func(kind, name string) bool {
		return kind == o.orgKind && (name == o.orgName || name == o.Name || strings.HasSuffix(o.Name, name) || strings.HasPrefix(o.Name, name))
	}
	tryFile := func(rel string) bool {
		file := cleanRel(path.Join(n.Dir, rel))
		data, err := p.fs.read(file)
		if err != nil {
			return false
		}
		f := ParseFile(file, data)
		for di, s := range f.Docs() {
			var m map[string]any
			if s.Doc.Root.Decode(&m) != nil {
				continue
			}
			if !targets(str(m, "kind"), str(m, "metadata", "name")) {
				continue
			}
			if keys, line, ok := docField(f, di, l.segs); ok {
				ident := FormatPath(l.segs)
				if ident == "metadata.name" || ident == "metadata.namespace" || ident == "kind" || ident == "apiVersion" {
					continue // the patch's target, not a value it sets
				}
				if v, ok := at(normalize(m), keys); ok && isScalar(v) && fmt.Sprint(v) != fmt.Sprint(l.value) {
					continue // a later transformer changes it
				}
				fs.Editable, fs.Via, fs.File, fs.Line, fs.docKeys, fs.doc = true, ViaPatch, file, line, keys, di
				if strings.HasSuffix(file, ".json") {
					fs.Editable, fs.Reason = false, "set in a JSON patch file: edit it in the Code tab"
				}
				return true
			}
		}
		return false
	}
	for _, it := range list(n.Data["patchesStrategicMerge"]) {
		if s, ok := it.(string); ok && !strings.Contains(s, "\n") && tryFile(s) {
			return true
		}
	}
	pointer := "/" + strings.Join(jsonPointer(l.keys), "/")
	for i, it := range list(n.Data["patches"]) {
		if rel := str(it, "path"); rel != "" {
			if tryFile(rel) {
				return true
			}
			if p.jsonPatchSets(cleanRel(path.Join(n.Dir, rel)), pointer) {
				fs.File, fs.Line = cleanRel(path.Join(n.Dir, rel)), 1
				fs.Reason = "set by a JSON patch (" + fs.File + "): edit the patch"
				return true
			}
		}
		if inline := str(it, "patch"); inline != "" && strings.Contains(inline, pointer) || strings.Contains(inline, l.segs[len(l.segs)-1].Key+":") && str(it, "target", "name") == o.orgName {
			fs.File, fs.Line = n.File, n.Doc.LocatePath([]string{"patches", itoa(i)})
			fs.Reason = "set by an inline patch in " + n.File + ": edit it there"
			return true
		}
	}
	for _, it := range list(n.Data["patchesJson6902"]) {
		if rel := str(it, "path"); rel != "" && p.jsonPatchSets(cleanRel(path.Join(n.Dir, rel)), pointer) {
			fs.File, fs.Line = cleanRel(path.Join(n.Dir, rel)), 1
			fs.Reason = "set by a JSON patch (" + fs.File + "): edit the patch"
			return true
		}
	}
	return false
}

func jsonPointer(keys []string) []string {
	out := make([]string, len(keys))
	for i, k := range keys {
		out[i] = strings.ReplaceAll(strings.ReplaceAll(k, "~", "~0"), "/", "~1")
	}
	return out
}

func (p *Project) jsonPatchSets(file, pointer string) bool {
	data, err := p.fs.read(file)
	if err != nil {
		return false
	}
	return strings.Contains(string(data), pointer)
}

// ---------------------------------------------------------------------------
// Helm

func (p *Project) helmField(o *Object, r *Rendered, hm *helmMap, l leaf, fs *fieldSource) {
	file := o.File
	fs.File, fs.Line = file, o.Line
	if hm == nil || hm.err != nil {
		reason := "the chart's source map could not be computed"
		if hm != nil && hm.err != nil {
			reason += ": " + hm.err.Error()
		}
		fs.Reason = reason
		return
	}
	so := hm.match(o)
	if so == nil {
		fs.Reason = "the template renders this object differently when values change: edit it in code"
		return
	}
	sv, ok := at(so.Obj, l.keys)
	if !ok {
		fs.Reason = "computed by the template: edit it in code"
		return
	}
	text := fmt.Sprint(sv)
	cur := fmt.Sprint(l.value)
	if n, isNum := toInt(sv); isNum && hm.numbers[n] != "" {
		key := hm.numbers[n]
		if hm.current[key] == cur {
			p.valuesField(r, hm, &valuesPattern{keys: []string{key}, parts: []string{"", ""}}, fs)
			return
		}
	}
	if pat := hm.pattern(text); pat != nil && isScalar(l.value) && pat.render(hm.current) == cur {
		p.valuesField(r, hm, pat, fs)
		return
	}
	if lit, ok := hm.literals[o.matchKey+"|"+strings.Join(l.keys, "\x00")]; ok && isScalar(l.value) {
		fs.Editable, fs.Via, fs.File, fs.Line, fs.literal = true, ViaTemplate, lit.file, lit.line, lit.literal
		return
	}
	fs.Line = p.templateKeyLine(file, o.Line, l.segs)
	fs.Reason = "computed by the template (not a values key or a literal): edit " + file + " in code"
}

// valuesField fills a field rendered from values keys.
func (p *Project) valuesField(r *Rendered, hm *helmMap, pat *valuesPattern, fs *fieldSource) {
	fs.ValuesKeys = pat.keys
	fs.helm = r.helm
	for _, k := range pat.keys {
		fs.cur = append(fs.cur, hm.current[k])
	}
	fs.pattern = pat
	if len(pat.keys) > 1 || pat.parts[0] != "" || pat.parts[len(pat.parts)-1] != "" {
		fs.Format = pat.describe()
	}
	for _, k := range pat.keys {
		file, line := p.valuesKeyFile(r, k)
		fs.valuesFiles = append(fs.valuesFiles, file)
		if fs.Via == "" {
			fs.File, fs.Line = file, line
		}
		fs.Via = ViaValues
	}
	if !pat.decomposable() {
		fs.Reason = "joins the values " + strings.Join(pat.keys, ", ") + " without a separator: edit them in " + fs.File
		return
	}
	fs.Editable = true
}

// valuesKeyFile is the values file that sets key (the last one that
// defines it), or where a write of it belongs: the environment's values
// file when one is active, else the last values file, else the chart's
// values.yaml.
func (p *Project) valuesKeyFile(r *Rendered, key string) (string, int) {
	h := r.helm
	segs, _ := ParsePath(key)
	keys := make([]string, len(segs))
	for i, s := range segs {
		keys[i] = s.Key
		if !s.isKey() {
			keys[i] = strconv.Itoa(s.Index)
		}
	}
	for i := len(h.valuesFiles) - 1; i >= 0; i-- {
		f := h.valuesFiles[i]
		data, err := p.fs.read(f)
		if err != nil {
			continue
		}
		d, err := compose.ParseDoc(f, data)
		if err != nil {
			continue
		}
		if k, _ := d.Get(keys...); k != nil {
			return f, k.Line
		}
		if n := d.Node(keys...); n != nil {
			return f, n.Line
		}
	}
	if len(h.valuesFiles) > 0 {
		return h.valuesFiles[len(h.valuesFiles)-1], 0
	}
	return path.Join(h.chartDir, "values.yaml"), 0
}

// templateKeyLine is the first line at or after from writing the deepest
// key of segs (for Locate on templates).
func (p *Project) templateKeyLine(file string, from int, segs []seg) int {
	data, err := p.fs.read(file)
	if err != nil {
		return from
	}
	lines := strings.Split(string(data), "\n")
	for i := len(segs) - 1; i >= 0; i-- {
		if !segs[i].isKey() {
			continue
		}
		re := regexp.MustCompile(`^\s*-?\s*["']?` + regexp.QuoteMeta(segs[i].Key) + `["']?\s*:`)
		for j := max(from-1, 0); j < len(lines); j++ {
			if re.MatchString(lines[j]) {
				return j + 1
			}
		}
	}
	return max(from, 1)
}

// Locate is the file and line a diagnostic about a field of o points at:
// the deepest existing key in the file that produced it (manifest,
// Kustomize patch or resource, Helm template), o's declaration otherwise.
// It never computes the Helm source map.
func (p *Project) Locate(o *Object, fieldPath string) (string, int) {
	segs, err := ParsePath(fieldPath)
	if err != nil {
		return o.File, o.Line
	}
	r := p.Source(o)
	if r != nil && r.Source.Kind == model.KubeHelm {
		return o.File, p.templateKeyLine(o.File, o.Line, segs)
	}
	if o.Doc < 0 || o.File == "" {
		return o.File, o.Line
	}
	data, err := p.fs.read(o.File)
	if err != nil {
		return o.File, o.Line
	}
	f := ParseFile(o.File, data)
	docs := f.Docs()
	if o.Doc >= len(docs) {
		return o.File, o.Line
	}
	s := docs[o.Doc]
	var m map[string]any
	if s.Doc.Root.Decode(&m) != nil {
		return o.File, o.Line
	}
	// Walk as deep as the document goes.
	for n := len(segs); n > 0; n-- {
		keys, missing, ok := concrete(normalize(m), segs[:n])
		if ok && !missing {
			return o.File, s.Line(s.Doc.LocatePath(keys))
		}
	}
	return o.File, o.Line
}
